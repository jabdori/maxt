fn render_native_method(operation: &Operation) -> String {
    let argument_lines = operation
        .arguments
        .iter()
        .map(|argument| {
            format!(
                "        {}: {},\n",
                snake_case(argument.name),
                rust_wire_type(argument.ty)
            )
        })
        .collect::<String>();
    let inline_arguments = operation
        .arguments
        .iter()
        .map(|argument| {
            format!(
                "{}: {}",
                snake_case(argument.name),
                rust_wire_type(argument.ty)
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    let inline = format!(
        "    pub async fn {}(&self{}{}) -> Result<{}, NativeError> {{\n",
        operation.rust_name,
        if inline_arguments.is_empty() {
            ""
        } else {
            ", "
        },
        inline_arguments,
        rust_wire_type(operation.result),
    );
    let mut output = if inline.trim_end().chars().count() <= 100 {
        inline
    } else {
        format!(
            "    pub async fn {}(\n        &self,\n{argument_lines}    ) -> Result<{}, NativeError> {{\n",
            operation.rust_name,
            rust_wire_type(operation.result),
        )
    };

    for argument in operation.arguments {
        let name = snake_case(argument.name);
        match argument.ty {
            ApiType::OptionalNamed("Market") => {
                output.push_str(&format!("        let {name} = {name}.map(Into::into);\n"));
            }
            ApiType::Named("OrderRequest" | "MarginRequest") => {
                output.push_str(&format!("        let {name} = {name}.try_into()?;\n"));
            }
            _ => {}
        }
    }

    if operation.rust_name == "positions" {
        output.push_str(
            "        let mut positions = self\n            .adapter\n            .positions(market.as_ref())\n            .await\n            .map_err(NativeError::from)?;\n        positions.retain(|position| !position.is_flat());\n        Ok(positions.into_iter().map(Into::into).collect())\n",
        );
    } else {
        let call_arguments = operation
            .arguments
            .iter()
            .map(native_call_argument)
            .collect::<Vec<_>>()
            .join(", ");
        if operation.result == ApiType::Unit {
            output.push_str(&format!(
                "        self.adapter.{}({call_arguments}).await",
                operation.rust_name
            ));
        } else {
            output.push_str(&format!(
                "        self.adapter\n            .{}({call_arguments})\n            .await",
                operation.rust_name
            ));
        }
        match operation.result {
            ApiType::List(_) | ApiType::PairList(_, _) => {
                output.push_str(
                    "\n            .map(|items| items.into_iter().map(Into::into).collect())",
                );
            }
            ApiType::Named(_) | ApiType::Page(_) | ApiType::Handle(_) => {
                output.push_str("\n            .map(Into::into)");
            }
            _ => {}
        }
        if operation.result == ApiType::Unit {
            output.push_str(".map_err(Into::into)\n");
        } else {
            output.push_str("\n            .map_err(Into::into)\n");
        }
    }
    output.push_str("    }\n");
    output
}

fn native_call_argument(argument: &Argument) -> String {
    let name = snake_case(argument.name);
    match argument.ty {
        ApiType::Named("Market") => format!("&{name}.into()"),
        ApiType::Named("MarketKind") => format!("{name}.into()"),
        ApiType::Named("OrderRequest" | "MarginRequest") => format!("&{name}"),
        ApiType::Named(_) => format!("&{name}.into()"),
        ApiType::OptionalNamed("Market") => format!("{name}.as_ref()"),
        ApiType::String => format!("&{name}"),
        _ => name,
    }
}

fn rust_wire_type(ty: ApiType) -> String {
    match ty {
        ApiType::String => "String".into(),
        ApiType::Boolean => "bool".into(),
        ApiType::Number => "u32".into(),
        ApiType::Named(name) => format!("Wire{name}"),
        ApiType::OptionalString => "Option<String>".into(),
        ApiType::OptionalNumber => "Option<u32>".into(),
        ApiType::OptionalNamed(name) => format!("Option<Wire{name}>"),
        ApiType::List(name) | ApiType::PairList(_, name) => format!("Vec<Wire{name}>"),
        ApiType::Page(name) => format!("Wire{name}Page"),
        ApiType::Handle(name) => format!("Wire{name}"),
        ApiType::HandleToken(name) => name.into(),
        ApiType::Unit => "()".into(),
        ApiType::MarketStream | ApiType::AccountStream => {
            unreachable!("stream façades remain handwritten")
        }
    }
}

fn snake_case(value: &str) -> String {
    value
        .chars()
        .enumerate()
        .fold(String::new(), |mut output, (index, character)| {
            if index > 0 && character.is_ascii_uppercase() {
                output.push('_');
            }
            output.push(character.to_ascii_lowercase());
            output
        })
}

fn pascal_case(value: &str) -> String {
    value
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut characters = part.chars();
            characters
                .next()
                .map(char::to_uppercase)
                .into_iter()
                .flatten()
                .chain(characters)
                .collect::<String>()
        })
        .collect()
}

fn render_method_declaration(output: &mut String, operation: &Operation) {
    if let Some(doc) = adapter_doc(operation.language_name) {
        output.push_str(doc);
    }
    let declaration = format!(
        "  Future<{}> {}({});\n",
        dart_type(operation.result),
        operation.language_name,
        dart_arguments(operation.arguments)
    );
    if declaration.trim_end().chars().count() <= 80 || operation.arguments.len() < 2 {
        output.push_str(&declaration);
    } else {
        output.push_str(&format!(
            "  Future<{}> {}(\n{}  );\n",
            dart_type(operation.result),
            operation.language_name,
            operation
                .arguments
                .iter()
                .map(|argument| format!("    {},\n", dart_argument(argument)))
                .collect::<String>()
        ));
    }
}

fn render_unsupported_method(output: &mut String, schema: &Schema, operation: &Operation) {
    let feature = schema
        .identifier("Feature")
        .and_then(|identifier| {
            identifier
                .variants
                .iter()
                .find(|variant| variant.wire_name == operation.feature)
        })
        .unwrap_or_else(|| panic!("unknown Feature wire name: {}", operation.feature));
    let signature = format!(
        "  Future<{}> {}({})",
        dart_type(operation.result),
        operation.language_name,
        dart_arguments(operation.arguments),
    );
    let call = format!("_unsupported(Feature.{})", dart_name(feature.rust_name));
    if signature.chars().count() + call.chars().count() + 5 <= 80 {
        output.push_str(&format!("  @override\n{signature} => {call};\n"));
    } else {
        output.push_str(&format!("  @override\n{signature} =>\n      {call};\n"));
    }
}

fn render_client_method(
    operation: &Operation,
    method: &maxt_bindings_common::schema::ClientMethod,
) -> String {
    let signature = format!(
        "{}  Future<{}> {}({})",
        client_doc(method.name).unwrap_or_default(),
        dart_type(operation.result),
        method.name,
        dart_arguments(method.arguments)
    );
    let body = match method.name {
        "trades" => {
            " async =>\n      _native.trades(market, checkedUint32(limit, field: 'limit'));"
        }
        "orderBook" => {
            " async =>\n      _native.orderBook(market, checkedUint32(depth, field: 'depth'));"
        }
        "candles" => {
            " async {\n    checkedUint32(request.limit, field: 'limit');\n    return _native.candles(request);\n  }"
        }
        "subscribe" => " =>\n      subscribeWith(subscription, defaultStreamConfig());",
        "subscribeWith" => {
            return format!(
                "{}  Future<MarketStream> subscribeWith(\n    Subscription subscription,\n    StreamConfig config,\n  ) async {{\n    validateStreamConfigIntegers(config);\n    return _native.subscribe(subscription, config);\n  }}\n",
                client_doc(method.name).unwrap_or_default()
            );
        }
        "openOrders" => " => _native.openOrders();",
        "openOrdersOn" => " => _native.openOrders(market);",
        "subscribeAccount" => " =>\n      subscribeAccountWith(defaultStreamConfig());",
        "subscribeAccountWith" => {
            " async {\n    validateStreamConfigIntegers(config);\n    return _native.subscribeAccount(config);\n  }"
        }
        "cancelOrder" => " =>\n      _native.cancelOrder(market, orderId);",
        "positions" => " async =>\n      _openPositions(await _native.positions());",
        "positionsOn" => " async =>\n      _openPositions(await _native.positions(market));",
        "fundingRates" | "fundingPayments" => {
            return format!(
                "{signature} async {{\n    checkedUint32(request.limit, field: 'limit');\n    return _native.{}(request);\n  }}\n",
                method.native_name
            );
        }
        _ => {
            let arguments = method
                .arguments
                .iter()
                .map(|argument| argument.name)
                .collect::<Vec<_>>()
                .join(", ");
            return format!(
                "{signature} => _native.{}({arguments});\n",
                method.native_name
            );
        }
    };
    format!("{signature}{body}\n")
}

fn adapter_doc(name: &str) -> Option<&'static str> {
    match name {
        "trades" => {
            Some("  /// 최근 체결을 최신순으로 반환하며, `limit`은 요청할 최대 개수입니다.\n")
        }
        "orderBook" => Some(
            "  /// 호가창 스냅샷을 반환하며, `depth`는 매수·매도 각 측의 최대 단계 수입니다.\n",
        ),
        "candles" => Some("  /// [CandleRequest] 조건에 맞는 캔들을 오래된 순서로 반환합니다.\n"),
        "subscribe" => Some(
            "  /// 시장 데이터를 구독합니다. 사용 후 [CloseableStream.close]를 호출해야 합니다.\n",
        ),
        _ => None,
    }
}

fn client_doc(name: &str) -> Option<&'static str> {
    match name {
        "trades" | "orderBook" | "candles" => adapter_doc(name),
        "subscribe" => Some("  /// 기본 연결 설정으로 시장 데이터를 구독합니다.\n"),
        "subscribeWith" => Some("  /// 지정한 연결 설정으로 시장 데이터를 구독합니다.\n"),
        _ => None,
    }
}

fn dart_arguments(arguments: &[Argument]) -> String {
    let required = arguments
        .iter()
        .take_while(|argument| argument.default.is_none())
        .map(dart_argument)
        .collect::<Vec<_>>();
    let optional = arguments
        .iter()
        .skip(required.len())
        .map(dart_argument)
        .collect::<Vec<_>>();
    match (required.is_empty(), optional.is_empty()) {
        (_, true) => required.join(", "),
        (true, false) => format!("[{}]", optional.join(", ")),
        (false, false) => format!("{}, [{}]", required.join(", "), optional.join(", ")),
    }
}

fn dart_argument(argument: &Argument) -> String {
    format!("{} {}", dart_type(argument.ty), argument.name)
}

fn dart_type(ty: ApiType) -> String {
    match ty {
        ApiType::String => "String".into(),
        ApiType::Boolean => "bool".into(),
        ApiType::Number => "int".into(),
        ApiType::Named(name) => name.into(),
        ApiType::OptionalString => "String?".into(),
        ApiType::OptionalNumber => "int?".into(),
        ApiType::OptionalNamed(name) => format!("{name}?"),
        ApiType::List(name) | ApiType::PairList(_, name) => format!("List<{name}>"),
        ApiType::Page(name) => format!("Page<{name}>"),
        ApiType::Handle(name) => name.into(),
        ApiType::HandleToken(name) => name.into(),
        ApiType::MarketStream => "MarketStream".into(),
        ApiType::AccountStream => "AccountStream".into(),
        ApiType::Unit => "void".into(),
    }
}

fn render_closed_identifier(
    output: &mut String,
    identifier: &maxt_bindings_common::schema::Identifier,
) {
    let variants = identifier
        .variants
        .iter()
        .map(|variant| dart_name(variant.rust_name))
        .collect::<Vec<_>>()
        .join(", ");
    let declaration = format!("enum {} {{ {variants} }}", identifier.name);
    if declaration.chars().count() <= 80 {
        output.push_str(&format!("{declaration}\n\n"));
    } else {
        output.push_str(&format!("enum {} {{\n", identifier.name));
        for variant in identifier.variants {
            output.push_str(&format!("  {},\n", dart_name(variant.rust_name)));
        }
        output.push_str("}\n\n");
    }
    output.push_str(&format!(
        "extension {}WireName on {} {{\n  String get wireName => switch (this) {{\n",
        identifier.name, identifier.name
    ));
    for variant in identifier.variants {
        output.push_str(&format!(
            "    {}.{} => '{}',\n",
            identifier.name,
            dart_name(variant.rust_name),
            variant.wire_name
        ));
    }
    output.push_str("  };\n}\n");
}

fn render_open_identifier(
    output: &mut String,
    identifier: &maxt_bindings_common::schema::Identifier,
) {
    output.push_str(&format!(
        "final class {} {{\n  const {}._(this.providerName, [this._isOther = false]);\n\n",
        identifier.name, identifier.name
    ));
    for variant in identifier.variants {
        let name = dart_name(variant.rust_name);
        let declaration = format!("  static const {name} = {}._('{name}');", identifier.name);
        if declaration.chars().count() <= 80 {
            output.push_str(&format!("{declaration}\n"));
        } else {
            output.push_str(&format!(
                "  static const {name} = {}._(\n    '{name}',\n  );\n",
                identifier.name
            ));
        }
    }
    output.push_str(&format!(
        "\n  factory {}.other(String providerName) =>\n      {}._(providerName, true);\n\n  final String providerName;\n  final bool _isOther;\n\n  bool get isOther => _isOther;\n\n  @override\n  bool operator ==(Object other) =>\n      other is {} &&\n      _isOther == other._isOther &&\n      providerName == other.providerName;\n\n  @override\n  int get hashCode => Object.hash(_isOther, providerName);\n\n  @override\n  String toString() => providerName;\n}}\n",
        identifier.name, identifier.name, identifier.name
    ));
}

fn dart_name(rust_name: &str) -> String {
    let mut characters = rust_name.chars();
    characters
        .next()
        .map(char::to_lowercase)
        .into_iter()
        .flatten()
        .chain(characters)
        .collect()
}

fn list(values: &[&str], indent: &str) -> String {
    let joined = values
        .iter()
        .map(|value| format!("'{value}'"))
        .collect::<Vec<_>>()
        .join(", ");
    if joined.len() <= 60 {
        format!("<String>[{joined}]")
    } else {
        let items = values
            .iter()
            .map(|value| format!("{indent}  '{value}',\n"))
            .collect::<String>();
        format!("<String>[\n{items}{indent}]")
    }
}

