fn render_dart_record_from_wire(name: &str, fields: &[Field]) -> String {
    let function = match name {
        "BinanceSpotOrderDetail" => "binanceSpotOrder".to_owned(),
        _ => lower_camel(name),
    };
    let fields = fields
        .iter()
        .map(|field| {
            let public = snake_to_lower_camel(field.name);
            let value = dart_from_wire_expression(field.name, &field.ty);
            format!("  {public}: {value},\n")
        })
        .collect::<String>();
    dart_named_constructor_function(
        &format!("{name} _{function}FromWire"),
        &format!("wire.Wire{name}"),
        name,
        &fields,
    ) + "\n"
}

fn dart_named_constructor_function(
    declaration: &str,
    parameter_type: &str,
    constructor: &str,
    fields: &str,
) -> String {
    let signature = format!("{declaration}({parameter_type} value)");
    if signature.len() > 80 {
        return format!(
            "{declaration}(\n  {parameter_type} value,\n) => {constructor}(\n{fields});\n"
        );
    }
    if signature.len() + constructor.len() + 5 > 80 {
        let fields = fields
            .lines()
            .map(|line| format!("    {line}\n"))
            .collect::<String>();
        return format!("{signature} =>\n    {constructor}(\n{fields}    );\n");
    }
    format!("{signature} => {constructor}(\n{fields});\n")
}

fn dart_constructor_call(
    signature: &str,
    constructor: &str,
    fields: &str,
) -> (String, String, String) {
    if signature.len() + constructor.len() + 4 <= 80 {
        (
            format!("{signature} => {constructor}\n"),
            fields.to_owned(),
            ");\n".to_owned(),
        )
    } else {
        (
            format!("{signature} =>\n    {constructor}\n"),
            fields.lines().map(|line| format!("    {line}\n")).collect(),
            "    );\n".to_owned(),
        )
    }
}

fn dart_from_wire_expression(name: &str, ty: &Type) -> String {
    let field = format!("value.{}", dart_wire_field(name, ty));
    dart_from_wire_value_expression(&field, ty)
}

fn dart_from_wire_value_expression(field: &str, ty: &Type) -> String {
    match ty {
        Type::String | Type::Boolean | Type::Number => field.to_owned(),
        Type::UnsignedInteger => field.to_owned(),
        Type::Decimal => format!("Decimal.parse({field})"),
        Type::Timestamp => format!("_timestampFromWire({field})!"),
        Type::Identifier("Network") => format!("_networkFromWire({field})"),
        Type::Identifier(identifier) => {
            format!("_{}FromWire({field})", lower_camel(identifier))
        }
        Type::Named(named) => format!(
            "_{}FromWire({field})",
            lower_camel(named.trim_end_matches("Wire"))
        ),
        Type::Optional(inner) => match inner.as_ref() {
            Type::String | Type::Boolean | Type::Number => field.to_owned(),
            Type::UnsignedInteger => field.to_owned(),
            Type::Decimal => format!("_decimalFromWire({field})"),
            Type::Timestamp => format!("_timestampFromWire({field})"),
            Type::Identifier("Network") => {
                dart_optional_expression(field, &format!("_networkFromWire({field}!)"))
            }
            Type::Identifier(identifier) => dart_optional_expression(
                field,
                &format!("_{}FromWire({field}!)", lower_camel(identifier)),
            ),
            Type::Named(named) => dart_optional_expression(
                field,
                &format!(
                    "_{}FromWire({field}!)",
                    lower_camel(named.trim_end_matches("Wire"))
                ),
            ),
            other => panic!("unsupported optional Dart wire field: {other:?}"),
        },
        Type::List(inner) => match inner.as_ref() {
            Type::String | Type::Boolean | Type::Number => field.to_owned(),
            Type::Decimal => format!("{field}.map(Decimal.parse).toList(growable: false)"),
            Type::Identifier("Network") => {
                format!("{field}.map(_networkFromWire).toList(growable: false)")
            }
            Type::Identifier(identifier) => format!(
                "{field}.map(_{}FromWire).toList(growable: false)",
                lower_camel(identifier)
            ),
            Type::Named(named) => format!(
                "{field}.map(_{}FromWire).toList(growable: false)",
                lower_camel(named.trim_end_matches("Wire"))
            ),
            other => panic!("unsupported Dart wire list field: {other:?}"),
        },
        Type::Tuple(_) => panic!("tuple record fields are not used by Dart DTOs"),
    }
}

fn dart_to_wire_expression(value: &str, ty: &Type, field: &str) -> String {
    match ty {
        Type::String | Type::Boolean => value.to_owned(),
        Type::Number => format!("checkedUint32({value}, field: '{field}')"),
        Type::UnsignedInteger => value.to_owned(),
        Type::Decimal => format!("{value}.toString()"),
        Type::Timestamp => format!("_timestampToWire({value})"),
        Type::Identifier("Network") => format!("_networkToWire({value})"),
        Type::Identifier(identifier) => {
            format!("_{}ToWire({value})", lower_camel(identifier))
        }
        Type::Named(named) => format!(
            "_{}ToWire({value})",
            lower_camel(named.trim_end_matches("Wire"))
        ),
        Type::Optional(inner) => match inner.as_ref() {
            Type::String | Type::Boolean => value.to_owned(),
            Type::Number => format!("checkedUint32({value}, field: '{field}')"),
            Type::UnsignedInteger => value.to_owned(),
            Type::Decimal => format!("{value}?.toString()"),
            Type::Timestamp => format!("_optionalTimestampToWire({value})"),
            Type::Identifier("Network") => {
                dart_optional_expression(value, &format!("_networkToWire({value}!)"))
            }
            Type::Identifier(identifier) => dart_optional_expression(
                value,
                &format!("_{}ToWire({value}!)", lower_camel(identifier)),
            ),
            Type::Named(named) => dart_optional_expression(
                value,
                &format!(
                    "_{}ToWire({value}!)",
                    lower_camel(named.trim_end_matches("Wire"))
                ),
            ),
            other => panic!("unsupported optional Dart model field: {other:?}"),
        },
        Type::List(inner) => match inner.as_ref() {
            Type::String | Type::Boolean | Type::Number => {
                format!("{value}.toList(growable: false)")
            }
            Type::Decimal => {
                format!("{value}.map((item) => item.toString()).toList(growable: false)")
            }
            Type::Identifier("Network") => {
                format!("{value}.map(_networkToWire).toList(growable: false)")
            }
            Type::Identifier(identifier) => format!(
                "{value}.map(_{}ToWire).toList(growable: false)",
                lower_camel(identifier)
            ),
            Type::Named(named) => format!(
                "{value}.map(_{}ToWire).toList(growable: false)",
                lower_camel(named.trim_end_matches("Wire"))
            ),
            other => panic!("unsupported Dart model list field: {other:?}"),
        },
        Type::Tuple(_) => panic!("tuple record fields are not used by Dart DTOs"),
    }
}

fn dart_wire_field(name: &str, ty: &Type) -> String {
    let mut name = snake_to_lower_camel(name);
    if matches!(ty, Type::Timestamp)
        || matches!(ty, Type::Optional(inner) if matches!(inner.as_ref(), Type::Timestamp))
    {
        name.push_str("Ns");
    }
    name
}

fn dart_arrow_function(signature: &str, expression: &str) -> String {
    if signature.len() + expression.len() + 5 <= 80 {
        format!("{signature} => {expression};\n")
    } else {
        format!("{signature} =>\n    {expression};\n")
    }
}

fn dart_optional_expression(value: &str, converted: &str) -> String {
    let inline = format!("{value} == null ? null : {converted}");
    if inline.len() <= 64 {
        inline
    } else {
        format!("{value} == null\n      ? null\n      : {converted}")
    }
}

fn snake_to_lower_camel(value: &str) -> String {
    let mut output = String::new();
    let mut uppercase = false;
    for character in value.chars() {
        if character == '_' {
            uppercase = true;
        } else if uppercase {
            output.push(character.to_ascii_uppercase());
            uppercase = false;
        } else {
            output.push(character);
        }
    }
    output
}

fn lower_camel(value: &str) -> String {
    let mut characters = value.chars();
    match characters.next() {
        Some(first) => first.to_ascii_lowercase().to_string() + characters.as_str(),
        None => String::new(),
    }
}

fn pascal_case(value: &str) -> String {
    value
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut characters = part.chars();
            characters
                .next()
                .map(char::to_uppercase)
                .into_iter()
                .flatten()
                .chain(characters)
                .collect::<String>()
        })
        .collect()
}

fn render_method_declaration(output: &mut String, operation: &Operation) {
    if let Some(doc) = adapter_doc(operation.language_name) {
        output.push_str(doc);
    }
    let declaration = format!(
        "  Future<{}> {}({});\n",
        dart_type(operation.result),
        operation.language_name,
        dart_arguments(operation.arguments)
    );
    if declaration.trim_end().chars().count() <= 80 || operation.arguments.len() < 2 {
        output.push_str(&declaration);
    } else {
        output.push_str(&format!(
            "  Future<{}> {}(\n{}  );\n",
            dart_type(operation.result),
            operation.language_name,
            operation
                .arguments
                .iter()
                .map(|argument| format!("    {},\n", dart_argument(argument)))
                .collect::<String>()
        ));
    }
}

fn render_unsupported_method(output: &mut String, schema: &Schema, operation: &Operation) {
    let feature = schema
        .identifier("Feature")
        .and_then(|identifier| {
            identifier
                .variants
                .iter()
                .find(|variant| variant.wire_name == operation.feature)
        })
        .unwrap_or_else(|| panic!("unknown Feature wire name: {}", operation.feature));
    let signature = format!(
        "  Future<{}> {}({})",
        dart_type(operation.result),
        operation.language_name,
        dart_arguments(operation.arguments),
    );
    let call = format!("_unsupported(Feature.{})", dart_name(feature.rust_name));
    if signature.chars().count() + call.chars().count() + 5 <= 80 {
        output.push_str(&format!("  @override\n{signature} => {call};\n"));
    } else {
        output.push_str(&format!("  @override\n{signature} =>\n      {call};\n"));
    }
}

