fn dart_provider_result_converter(result: ApiType) -> String {
    match result {
        ApiType::Named(model) => format!("_{}FromWire", lower_camel(model)),
        ApiType::List(model) => format!(
            "(values) => values.map(_{}FromWire).toList(growable: false)",
            lower_camel(model)
        ),
        ApiType::Page(model) => format!("_{}PageFromWire", lower_camel(model)),
        ApiType::String => "(value) => value".to_owned(),
        other => panic!(
            "generated Dart provider method has unsupported result {:?}",
            other
        ),
    }
}

fn provider_stream_base(event: &str) -> &str {
    event.strip_suffix("Event").unwrap_or(event)
}

fn provider_stream_type(event: &str) -> String {
    let base = provider_stream_base(event);
    if base.ends_with("Stream") {
        base.to_owned()
    } else {
        format!("{base}Stream")
    }
}

fn generated_provider_stream_entries(schema: &Schema) -> Vec<(&'static str, &'static str, bool)> {
    let mut entries = Vec::new();
    for provider in schema.providers {
        for method in provider.methods.iter().filter(|method| {
            uses_generated_native_provider_bridge(provider.exchange, method.rust_name)
        }) {
            let (event, account) = match method.result {
                ApiType::ProviderMarketStream(event) => (event, false),
                ApiType::ProviderAccountStream(event) => (event, true),
                _ => continue,
            };
            if !entries.iter().any(|(exchange, existing, kind)| {
                *exchange == provider.exchange && *existing == event && *kind == account
            }) {
                entries.push((provider.exchange, event, account));
            }
        }
    }
    entries
}

pub(crate) fn render_delegate_methods(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\npart of 'adapters.dart';\n\n/// Base class that delegates common calls to another [Adapter] implementation.\nabstract base class GeneratedNativeDelegate extends AdapterBase {\n  /// The adapter that performs the actual call.\n  Future<Adapter> get delegateAdapter;\n",
    );
    for operation in schema.adapter_operations.iter().filter(|operation| {
        !matches!(
            operation.result,
            ApiType::MarketStream | ApiType::AccountStream
        )
    }) {
        let arguments = operation
            .arguments
            .iter()
            .map(|argument| argument.name)
            .collect::<Vec<_>>()
            .join(", ");
        let signature = format!(
            "  Future<{}> {}({}) async =>",
            dart_type(operation.result),
            operation.language_name,
            dart_arguments(operation.arguments),
        );
        let call = format!(
            "(await delegateAdapter).{}({arguments});",
            operation.language_name
        );
        output.push('\n');
        if let Some(doc) = adapter_doc(operation.language_name) {
            output.push_str(doc);
        }
        output.push_str("  @override\n");
        if signature.chars().count() + call.chars().count() < 80 {
            output.push_str(&format!("{signature} {call}\n"));
        } else {
            output.push_str(&format!("{signature}\n      {call}\n"));
        }
    }
    output.push_str("}\n");
    output
}

