fn render_rust_wire_identifier(identifier: &maxt_bindings_common::schema::Identifier) -> String {
    let name = identifier.name;
    let variants = identifier
        .variants
        .iter()
        .map(|variant| format!("    {},\n", variant.rust_name))
        .collect::<String>();
    let to_arms = identifier
        .variants
        .iter()
        .map(|variant| {
            format!(
                "            maxt::{name}::{} => Self::{},\n",
                variant.rust_name, variant.rust_name
            )
        })
        .collect::<String>();
    let fallback = identifier
        .variants
        .iter()
        .find(|variant| variant.rust_name == "Unknown")
        .map(|_| "            _ => Self::Unknown,\n")
        .unwrap_or("            _ => unreachable!(\"new identifier variant requires a Dart wire variant\"),\n");
    let from_arms = identifier
        .variants
        .iter()
        .map(|variant| {
            format!(
                "            Wire{name}::{} => Self::{},\n",
                variant.rust_name, variant.rust_name
            )
        })
        .collect::<String>();
    format!(
        "\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum Wire{name} {{\n{variants}}}\n\nimpl From<maxt::{name}> for Wire{name} {{\n    fn from(value: maxt::{name}) -> Self {{\n        match value {{\n{to_arms}{fallback}        }}\n    }}\n}}\n\nimpl From<Wire{name}> for maxt::{name} {{\n    fn from(value: Wire{name}) -> Self {{\n        match value {{\n{from_arms}        }}\n    }}\n}}\n"
    )
}

