fn rust_wire_field(name: &str, ty: &Type) -> String {
    let timestamp = matches!(ty, Type::Timestamp)
        || matches!(ty, Type::Optional(inner) if matches!(inner.as_ref(), Type::Timestamp));
    if timestamp {
        format!("{name}_ns")
    } else {
        name.to_owned()
    }
}

