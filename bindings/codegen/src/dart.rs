use maxt_bindings_common::schema::{
    ApiType, Argument, Operation, ProviderMethodKind, Schema, Type,
};

pub(crate) fn render(schema: &Schema) -> String {
    let mut output =
        String::from("// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\n");
    output.push_str(&format!(
        "const exchanges = {};\n",
        list(&schema.exchanges, "")
    ));
    output.push_str(&format!(
        "const features = {};\n",
        list(&schema.features, "")
    ));
    output.push_str(&format!(
        "const errorVariants = {};\n",
        list(schema.errors, "")
    ));
    let operations = schema
        .adapter_operations
        .iter()
        .map(|value| value.language_name)
        .collect::<Vec<_>>();
    output.push_str(&format!(
        "const adapterOperations = {};\n",
        list(&operations, "")
    ));
    output.push_str(&format!(
        "const clientMembers = {};\n",
        list(schema.client_members, "")
    ));
    output.push_str("const providerMethods = <String, List<String>>{\n");
    for provider in schema.providers {
        let methods = provider
            .methods
            .iter()
            .map(|method| method.name)
            .collect::<Vec<_>>();
        output.push_str(&format!(
            "  '{}': {},\n",
            provider.exchange,
            list(&methods, "  ")
        ));
    }
    output.push_str("};\n");
    output
}

pub(crate) fn render_identifiers(schema: &Schema) -> String {
    let mut output =
        String::from("// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\n");

    for (index, identifier) in schema.identifiers.iter().enumerate() {
        if identifier.open {
            render_open_identifier(&mut output, identifier);
        } else {
            render_closed_identifier(&mut output, identifier);
        }
        if index + 1 < schema.identifiers.len() {
            output.push('\n');
        }
    }

    output
}

pub(crate) fn render_adapter_api(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\n\
         import 'errors.dart';\n\
         import 'models.dart';\n\
         import 'stream.dart';\n\n\
         abstract interface class GeneratedAdapterContract {\n\
         \x20 Exchange get exchange;\n\n\
         \x20 Set<Feature> get features;\n\n\
         \x20 bool supports(Feature feature);\n",
    );
    for operation in schema.adapter_operations {
        output.push('\n');
        render_method_declaration(&mut output, operation);
    }
    output.push_str("}\n\nabstract base class GeneratedAdapterDefaults\n    implements GeneratedAdapterContract {\n  Future<T> _unsupported<T>(Feature feature) => Future<T>.error(\n    UnsupportedError(\n      feature: feature,\n      exchange: exchange,\n      detail: '${exchange.id} has no endpoint for ${feature.wireName}',\n    ),\n  );\n\n  @override\n  bool supports(Feature feature) => features.contains(feature);\n");
    for operation in schema
        .adapter_operations
        .iter()
        .filter(|operation| operation.language_name != "subscribe")
    {
        output.push('\n');
        render_unsupported_method(&mut output, schema, operation);
    }
    output.push_str("}\n");
    output
}

pub(crate) fn render_client_api(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\n\
         import 'adapter.dart';\n\
         import 'adapters.dart'\n\
         \x20   show NativeClientDelegate, checkedUint32, validateStreamConfigIntegers;\n\
         import 'models.dart';\n\
         import 'runtime.dart';\n\
         import 'stream.dart';\n\n\
         abstract base class GeneratedClient<A extends Adapter> {\n\
         \x20 GeneratedClient(this.adapter)\n\
         \x20   : _native = NativeClientDelegate.fromAdapter(adapter);\n\n\
         \x20 final A adapter;\n\
         \x20 final NativeClientDelegate _native;\n\n\
         \x20 Exchange get exchange => _native.exchange;\n\n\
         \x20 bool supports(Feature feature) => _native.supports(feature);\n",
    );
    for operation in schema.adapter_operations {
        for method in operation.client_methods {
            output.push('\n');
            output.push_str(&render_client_method(operation, method));
        }
    }
    output.push_str("\n  static List<Position> _openPositions(List<Position> positions) =>\n      positions.where((position) => !position.isFlat).toList(growable: false);\n}\n");
    output
}

pub(crate) fn render_native_client_api(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\nuse super::*;\n\nimpl NativeClient {\n",
    );
    for (index, operation) in schema
        .adapter_operations
        .iter()
        .filter(|operation| {
            !matches!(
                operation.result,
                ApiType::MarketStream | ApiType::AccountStream
            )
        })
        .enumerate()
    {
        if index > 0 {
            output.push('\n');
        }
        output.push_str(&render_native_method(operation));
    }
    output.push_str("}\n");
    output
}

pub(crate) fn render_rust_adapter_dispatch(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\nuse super::*;\n\n#[rustfmt::skip]\npub(super) fn dispatch(call: CommonAdapterCall) -> Option<(AdapterCall, ExpectedReply)> {\n    match call {\n",
    );
    for operation in schema.adapter_operations.iter().filter(|operation| {
        !matches!(
            operation.result,
            ApiType::MarketStream | ApiType::AccountStream
        )
    }) {
        let variant = pascal_case(operation.rust_name);
        let fields = operation
            .arguments
            .iter()
            .map(|argument| snake_case(argument.name))
            .collect::<Vec<_>>();
        let pattern = if fields.is_empty() {
            format!("CommonAdapterCall::{variant}")
        } else {
            format!("CommonAdapterCall::{variant} {{ {} }}", fields.join(", "))
        };
        let mapped_fields = operation
            .arguments
            .iter()
            .map(|argument| {
                let name = snake_case(argument.name);
                let value = match argument.ty {
                    ApiType::Named(_) => format!("{name}.into()"),
                    ApiType::OptionalNamed(_) => format!("{name}.map(Into::into)"),
                    _ => name.clone(),
                };
                format!("{name}: {value}")
            })
            .collect::<Vec<_>>();
        let expected = if operation.result == ApiType::Unit {
            "Unit".to_owned()
        } else {
            variant.clone()
        };
        if mapped_fields.is_empty() {
            let arm = format!(
                "        {pattern} => Some((AdapterCall::{variant}, ExpectedReply::{expected})),\n"
            );
            if arm.trim_end().chars().count() <= 100 {
                output.push_str(&arm);
            } else {
                output.push_str(&format!(
                    "        {pattern} => {{\n            Some((AdapterCall::{variant}, ExpectedReply::{expected}))\n        }}\n"
                ));
            }
        } else {
            output.push_str(&format!(
                "        {pattern} => Some((\n            AdapterCall::{variant} {{\n"
            ));
            let inline_fields = mapped_fields
                .iter()
                .map(|field| {
                    let (name, value) = field.split_once(": ").expect("generated field");
                    if name == value {
                        name.to_owned()
                    } else {
                        field.clone()
                    }
                })
                .collect::<Vec<_>>()
                .join(", ");
            let inline = format!("            AdapterCall::{variant} {{ {inline_fields} }},\n");
            if inline.trim_end().chars().count() <= 100 {
                output.truncate(
                    output.len() - format!("            AdapterCall::{variant} {{\n").len(),
                );
                output.push_str(&inline);
            } else {
                for field in mapped_fields {
                    let (name, value) = field.split_once(": ").expect("generated field");
                    if name == value {
                        output.push_str(&format!("                {name},\n"));
                    } else {
                        output.push_str(&format!("                {field},\n"));
                    }
                }
                output.push_str("            },\n");
            }
            output.push_str(&format!(
                "            ExpectedReply::{expected},\n        )),\n"
            ));
        }
    }
    output.push_str("        _ => None,\n    }\n}\n");
    output
}

pub(crate) fn render_provider_guard(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n// ignore_for_file: unused_element\n\npart of 'adapters.dart';\n\nT _generatedProviderValue<T>() => throw StateError('compile-time API guard');\n\nvoid _generatedProviderGuard({\n",
    );
    for provider in schema.providers {
        output.push_str(&format!(
            "  required {} {},\n",
            provider.adapter, provider.exchange
        ));
    }
    output.push_str("}) {\n");
    for provider in schema.providers {
        for constructor in provider.constructors {
            let name = if constructor.name == "constructor" {
                provider.adapter.to_owned()
            } else {
                format!("{}.{}", provider.adapter, constructor.name)
            };
            let arguments = constructor
                .arguments
                .iter()
                .filter(|argument| argument.default.is_none())
                .map(|argument| format!("_generatedProviderValue<{}>()", dart_type(argument.ty)))
                .collect::<Vec<_>>()
                .join(", ");
            output.push_str(&format!("  {name}({arguments});\n"));
        }
        for method in provider.methods {
            if method.kind == ProviderMethodKind::Property {
                output.push_str(&format!("  {}.{};\n", provider.exchange, method.name));
                continue;
            }
            let arguments = method
                .arguments
                .iter()
                .filter(|argument| argument.default.is_none())
                .map(|argument| format!("_generatedProviderValue<{}>()", dart_type(argument.ty)))
                .collect::<Vec<_>>()
                .join(", ");
            let call = format!("  {}.{}({arguments});", provider.exchange, method.name);
            if call.chars().count() <= 80 || method.arguments.len() < 2 {
                output.push_str(&format!("{call}\n"));
            } else {
                output.push_str(&format!("  {}.{}(\n", provider.exchange, method.name));
                for argument in method
                    .arguments
                    .iter()
                    .filter(|argument| argument.default.is_none())
                {
                    output.push_str(&format!(
                        "    _generatedProviderValue<{}>(),\n",
                        dart_type(argument.ty)
                    ));
                }
                output.push_str("  );\n");
            }
        }
    }
    output.push_str("}\n");
    output
}

pub(crate) fn render_provider_methods(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\npart of 'adapters.dart';\n",
    );
    for provider in schema.providers {
        output.push_str(&format!(
            "\nextension {}GeneratedMethods on {} {{\n",
            provider.adapter, provider.adapter
        ));
        for (index, method) in provider
            .methods
            .iter()
            .filter(|method| method.kind == ProviderMethodKind::Async)
            .enumerate()
        {
            if index > 0 {
                output.push('\n');
            }
            output.push_str(provider_method_source(provider.exchange, method.rust_name));
        }
        output.push_str("}\n");
    }
    output
}

pub(crate) fn render_delegate_methods(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\npart of 'adapters.dart';\n\nabstract base class GeneratedNativeDelegate extends AdapterBase {\n  Future<Adapter> get delegateAdapter;\n",
    );
    for operation in schema.adapter_operations.iter().filter(|operation| {
        !matches!(
            operation.result,
            ApiType::MarketStream | ApiType::AccountStream
        )
    }) {
        let arguments = operation
            .arguments
            .iter()
            .map(|argument| argument.name)
            .collect::<Vec<_>>()
            .join(", ");
        let signature = format!(
            "  Future<{}> {}({}) async =>",
            dart_type(operation.result),
            operation.language_name,
            dart_arguments(operation.arguments),
        );
        let call = format!(
            "(await delegateAdapter).{}({arguments});",
            operation.language_name
        );
        output.push_str("\n  @override\n");
        if signature.chars().count() + call.chars().count() < 80 {
            output.push_str(&format!("{signature} {call}\n"));
        } else {
            output.push_str(&format!("{signature}\n      {call}\n"));
        }
    }
    output.push_str("}\n");
    output
}

pub(crate) fn render_wire_shape_guard(schema: &Schema) -> String {
    const PROJECTED_RECORDS: &[&str] = &[
        "StreamConfigWire",
        "SubscriptionWire",
        "PageWire",
        "UpbitMarketEventWire",
        "BithumbMarketAlertWire",
        "BinanceListenKeyWire",
        "HyperliquidLedgerEntryWire",
        "UpbitOptionsWire",
        "BithumbOptionsWire",
        "BinanceOptionsWire",
        "HyperliquidOptionsWire",
        "NativeStreamReferenceWire",
    ];
    const PROJECTED_UNIONS: &[&str] = &[
        "SizeWire",
        "FeedWire",
        "MarketEventWire",
        "AccountEventWire",
        "MarketStreamItemWire",
        "AccountStreamItemWire",
        "ErrorWire",
        "AdapterCallWire",
        "AdapterReplyWire",
    ];
    const WIRE_IDENTIFIERS: &[(&str, &str)] = &[
        ("Exchange", "WireExchange"),
        ("Feature", "WireFeature"),
        ("MarketKind", "WireMarketKind"),
        ("MarketStatus", "WireMarketStatus"),
        ("Side", "WireSide"),
        ("Interval", "WireInterval"),
        ("MarginMode", "WireMarginMode"),
        ("OrderStatus", "WireOrderStatus"),
        ("OrderType", "WireOrderType"),
        ("TimeInForce", "WireTimeInForce"),
        ("SizeKind", "WireSizeKind"),
        ("BithumbAlertStep", "WireBithumbAlertStep"),
        ("ExchangeErrorKind", "WireExchangeErrorKind"),
    ];
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n#![allow(dead_code)]\n\nuse super::*;\n",
    );
    for record in &schema.records {
        if PROJECTED_RECORDS.contains(&record.name) {
            continue;
        }
        assert!(
            record.type_parameters.is_empty(),
            "unclassified generic Dart wire record: {}",
            record.name
        );
        let wire_name = format!(
            "Wire{}",
            record
                .name
                .strip_suffix("Wire")
                .unwrap_or_else(|| panic!("Dart wire record needs Wire suffix: {}", record.name))
        );
        output.push_str(&format!(
            "\nfn _guard_{}(value: {wire_name}) {{\n    let {wire_name} {{\n",
            snake_case(record.name)
        ));
        for field in &record.fields {
            let name = rust_wire_field(field.name, &field.ty);
            output.push_str(&format!("        {name}: _,\n"));
        }
        output.push_str("    } = value;\n}\n");
    }
    for union in &schema.unions {
        assert!(
            PROJECTED_UNIONS.contains(&union.name),
            "unclassified Dart wire union: {}",
            union.name
        );
    }
    let error_union = schema
        .unions
        .iter()
        .find(|union| union.name == "ErrorWire")
        .expect("ErrorWire schema");
    let mut error_fields = error_union
        .variants
        .iter()
        .flat_map(|variant| variant.fields.iter().map(|field| field.name))
        .collect::<std::collections::BTreeSet<_>>();
    error_fields.extend(["kind", "retryable", "rate_limited"]);
    output.push_str("\nfn _guard_native_error(value: NativeError) {\n    let NativeError {\n");
    for field in error_fields {
        output.push_str(&format!("        {field}: _,\n"));
    }
    output.push_str("    } = value;\n}\n\nfn _guard_native_error_kind(value: NativeErrorKind) {\n    match value {\n");
    for error in schema.errors {
        output.push_str(&format!(
            "        NativeErrorKind::{} => {{}}\n",
            pascal_case(error)
        ));
    }
    output.push_str("    }\n}\n");
    for (identifier_name, wire_name) in WIRE_IDENTIFIERS {
        let identifier = schema
            .identifier(identifier_name)
            .unwrap_or_else(|| panic!("missing identifier: {identifier_name}"));
        output.push_str(&format!(
            "\nfn _guard_{}(value: {wire_name}) {{\n    match value {{\n",
            snake_case(identifier_name)
        ));
        for variant in identifier.variants {
            output.push_str(&format!(
                "        {wire_name}::{} => {{}}\n",
                variant.rust_name
            ));
        }
        output.push_str("    }\n}\n");
    }
    output
}

fn rust_wire_field(name: &str, ty: &Type) -> String {
    let timestamp = matches!(ty, Type::Timestamp)
        || matches!(ty, Type::Optional(inner) if matches!(inner.as_ref(), Type::Timestamp));
    if timestamp {
        format!("{name}_ns")
    } else {
        name.to_owned()
    }
}

