use maxt_bindings_common::schema::Schema;

pub(crate) fn render(schema: &Schema) -> String {
    let mut output =
        String::from("// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\n");
    output.push_str(&format!(
        "const exchanges = {};\n",
        list(&schema.exchanges, "")
    ));
    output.push_str(&format!(
        "const features = {};\n",
        list(&schema.features, "")
    ));
    output.push_str(&format!(
        "const errorVariants = {};\n",
        list(schema.errors, "")
    ));
    let operations = schema
        .adapter_operations
        .iter()
        .map(|value| value.language_name)
        .collect::<Vec<_>>();
    output.push_str(&format!(
        "const adapterOperations = {};\n",
        list(&operations, "")
    ));
    output.push_str(&format!(
        "const clientMembers = {};\n",
        list(schema.client_members, "")
    ));
    output.push_str("const providerMethods = <String, List<String>>{\n");
    for provider in schema.providers {
        let methods = provider
            .methods
            .iter()
            .map(|method| method.name)
            .collect::<Vec<_>>();
        output.push_str(&format!(
            "  '{}': {},\n",
            provider.exchange,
            list(&methods, "  ")
        ));
    }
    output.push_str("};\n");
    output
}

pub(crate) fn render_identifiers(schema: &Schema) -> String {
    let mut output =
        String::from("// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\n");

    for (index, identifier) in schema.identifiers.iter().enumerate() {
        if identifier.open {
            render_open_identifier(&mut output, identifier);
        } else {
            render_closed_identifier(&mut output, identifier);
        }
        if index + 1 < schema.identifiers.len() {
            output.push('\n');
        }
    }

    output
}

fn render_closed_identifier(
    output: &mut String,
    identifier: &maxt_bindings_common::schema::Identifier,
) {
    let variants = identifier
        .variants
        .iter()
        .map(|variant| dart_name(variant.rust_name))
        .collect::<Vec<_>>()
        .join(", ");
    let declaration = format!("enum {} {{ {variants} }}", identifier.name);
    if declaration.chars().count() <= 80 {
        output.push_str(&format!("{declaration}\n\n"));
    } else {
        output.push_str(&format!("enum {} {{\n", identifier.name));
        for variant in identifier.variants {
            output.push_str(&format!("  {},\n", dart_name(variant.rust_name)));
        }
        output.push_str("}\n\n");
    }
    output.push_str(&format!(
        "extension {}WireName on {} {{\n  String get wireName => switch (this) {{\n",
        identifier.name, identifier.name
    ));
    for variant in identifier.variants {
        output.push_str(&format!(
            "    {}.{} => '{}',\n",
            identifier.name,
            dart_name(variant.rust_name),
            variant.wire_name
        ));
    }
    output.push_str("  };\n}\n");
}

fn render_open_identifier(
    output: &mut String,
    identifier: &maxt_bindings_common::schema::Identifier,
) {
    output.push_str(&format!(
        "final class {} {{\n  const {}._(this.providerName, [this._isOther = false]);\n\n",
        identifier.name, identifier.name
    ));
    for variant in identifier.variants {
        let name = dart_name(variant.rust_name);
        let declaration = format!("  static const {name} = {}._('{name}');", identifier.name);
        if declaration.chars().count() <= 80 {
            output.push_str(&format!("{declaration}\n"));
        } else {
            output.push_str(&format!(
                "  static const {name} = {}._(\n    '{name}',\n  );\n",
                identifier.name
            ));
        }
    }
    output.push_str(&format!(
        "\n  factory {}.other(String providerName) =>\n      {}._(providerName, true);\n\n  final String providerName;\n  final bool _isOther;\n\n  bool get isOther => _isOther;\n\n  @override\n  bool operator ==(Object other) =>\n      other is {} &&\n      _isOther == other._isOther &&\n      providerName == other.providerName;\n\n  @override\n  int get hashCode => Object.hash(_isOther, providerName);\n\n  @override\n  String toString() => providerName;\n}}\n",
        identifier.name, identifier.name, identifier.name
    ));
}

fn dart_name(rust_name: &str) -> String {
    let mut characters = rust_name.chars();
    characters
        .next()
        .map(char::to_lowercase)
        .into_iter()
        .flatten()
        .chain(characters)
        .collect()
}

fn list(values: &[&str], indent: &str) -> String {
    let joined = values
        .iter()
        .map(|value| format!("'{value}'"))
        .collect::<Vec<_>>()
        .join(", ");
    if joined.len() <= 60 {
        format!("<String>[{joined}]")
    } else {
        let items = values
            .iter()
            .map(|value| format!("{indent}  '{value}',\n"))
            .collect::<String>();
        format!("<String>[\n{items}{indent}]")
    }
}

#[cfg(test)]
mod tests {
    use maxt_bindings_common::schema::binding_schema;

    use super::render_identifiers;

    #[test]
    fn identifiers_are_rendered_from_the_schema() {
        let output = render_identifiers(&binding_schema());

        assert!(output.contains("enum BinanceMarket { spot, usdMFutures }"));
        assert!(output.contains("BinanceMarket.usdMFutures => 'usd_m'"));
        assert!(output.contains("final class HyperliquidLedgerKind"));
        assert!(output.contains(
            "static const vaultDistribution = HyperliquidLedgerKind._('vaultDistribution');"
        ));
        assert!(output.contains("factory HyperliquidLedgerKind.other(String providerName)"));
    }
}
