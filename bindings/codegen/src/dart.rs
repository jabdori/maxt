fn render_native_method(operation: &Operation) -> String {
    let argument_lines = operation
        .arguments
        .iter()
        .map(|argument| {
            format!(
                "        {}: {},\n",
                snake_case(argument.name),
                rust_wire_type(argument.ty)
            )
        })
        .collect::<String>();
    let inline_arguments = operation
        .arguments
        .iter()
        .map(|argument| {
            format!(
                "{}: {}",
                snake_case(argument.name),
                rust_wire_type(argument.ty)
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    let inline = format!(
        "    pub async fn {}(&self{}{}) -> Result<{}, NativeError> {{\n",
        operation.rust_name,
        if inline_arguments.is_empty() {
            ""
        } else {
            ", "
        },
        inline_arguments,
        rust_wire_type(operation.result),
    );
    let mut output = if inline.trim_end().chars().count() <= 100 {
        inline
    } else {
        format!(
            "    pub async fn {}(\n        &self,\n{argument_lines}    ) -> Result<{}, NativeError> {{\n",
            operation.rust_name,
            rust_wire_type(operation.result),
        )
    };

    for argument in operation.arguments {
        let name = snake_case(argument.name);
        match argument.ty {
            ApiType::OptionalNamed("Market") => {
                output.push_str(&format!("        let {name} = {name}.map(Into::into);\n"));
            }
            ApiType::Named(
                "OrderRequest"
                | "OrderLookupRequest"
                | "CancelOrdersRequest"
                | "OrderHistoryRequest"
                | "MarginRequest"
                | "DepositAddressRequest"
                | "WithdrawRequest"
                | "TransferLookupRequest"
                | "TransferHistoryRequest",
            ) => {
                output.push_str(&format!("        let {name} = {name}.try_into()?;\n"));
            }
            _ => {}
        }
    }

    if operation.rust_name == "positions" {
        output.push_str(
            "        let mut positions = self\n            .adapter\n            .positions(market.as_ref())\n            .await\n            .map_err(NativeError::from)?;\n        positions.retain(|position| !position.is_flat());\n        Ok(positions.into_iter().map(Into::into).collect())\n",
        );
    } else {
        let call_arguments = operation
            .arguments
            .iter()
            .map(native_call_argument)
            .collect::<Vec<_>>()
            .join(", ");
        if operation.result == ApiType::Unit {
            let inline = format!(
                "        self.adapter.{}({call_arguments}).await.map_err(Into::into)\n",
                operation.rust_name
            );
            if inline.trim_end().chars().count() <= 80 {
                output.push_str(&inline);
            } else {
                output.push_str(&format!(
                    "        self.adapter\n            .{}({call_arguments})\n            .await\n            .map_err(Into::into)\n",
                    operation.rust_name
                ));
            }
        } else {
            output.push_str(&format!(
                "        self.adapter\n            .{}({call_arguments})\n            .await",
                operation.rust_name
            ));
            match operation.result {
                ApiType::List(_) | ApiType::PairList(_, _) => {
                    output.push_str(
                        "\n            .map(|items| items.into_iter().map(Into::into).collect())",
                    );
                }
                ApiType::Named(_) | ApiType::Page(_) | ApiType::Handle(_) => {
                    output.push_str("\n            .map(Into::into)");
                }
                _ => {}
            }
            output.push_str("\n            .map_err(Into::into)\n");
        }
    }
    output.push_str("    }\n");
    output
}

fn native_call_argument(argument: &Argument) -> String {
    let name = snake_case(argument.name);
    match argument.ty {
        ApiType::Named("Market") => format!("&{name}.into()"),
        ApiType::Named("MarketKind") => format!("{name}.into()"),
        ApiType::Named(
            "OrderRequest"
            | "OrderLookupRequest"
            | "CancelOrdersRequest"
            | "OrderHistoryRequest"
            | "MarginRequest"
            | "DepositAddressRequest"
            | "WithdrawRequest"
            | "TransferLookupRequest"
            | "TransferHistoryRequest",
        ) => format!("&{name}"),
        ApiType::Named(_) => format!("&{name}.into()"),
        ApiType::OptionalNamed("Market") => format!("{name}.as_ref()"),
        ApiType::String => format!("&{name}"),
        _ => name,
    }
}

fn rust_wire_type(ty: ApiType) -> String {
    match ty {
        ApiType::Client => unreachable!("client arguments are handled by the client façade"),
        ApiType::String => "String".into(),
        ApiType::Boolean => "bool".into(),
        ApiType::Number => "u32".into(),
        ApiType::Named(name) => format!("Wire{name}"),
        ApiType::OptionalString => "Option<String>".into(),
        ApiType::OptionalNumber => "Option<u32>".into(),
        ApiType::OptionalNamed(name) => format!("Option<Wire{name}>"),
        ApiType::List(name) | ApiType::PairList(_, name) => format!("Vec<Wire{name}>"),
        ApiType::Page(name) => format!("Wire{name}Page"),
        ApiType::Handle(name) => format!("Wire{name}"),
        ApiType::HandleToken(name) => name.into(),
        ApiType::Unit => "()".into(),
        ApiType::MarketStream | ApiType::AccountStream => {
            unreachable!("stream façades remain handwritten")
        }
    }
}

fn snake_case(value: &str) -> String {
    value
        .chars()
        .enumerate()
        .fold(String::new(), |mut output, (index, character)| {
            if index > 0 && character.is_ascii_uppercase() {
                output.push('_');
            }
            output.push(character.to_ascii_lowercase());
            output
        })
}

fn render_dart_record_converter(name: &str, fields: &[Field]) -> String {
    let function = lower_camel(name);
    let from_fields = fields
        .iter()
        .map(|field| {
            let public = snake_to_lower_camel(field.name);
            let value = if field.name == "cursor" {
                "value.cursor == null ? null : Cursor(value.cursor!)".to_owned()
            } else {
                dart_from_wire_expression(field.name, &field.ty)
            };
            if name == "Market" {
                format!("  {value},\n")
            } else {
                format!("  {public}: {value},\n")
            }
        })
        .collect::<String>();
    let to_fields = fields
        .iter()
        .map(|field| {
            let public = snake_to_lower_camel(field.name);
            let wire = dart_wire_field(field.name, &field.ty);
            let value = if field.name == "cursor" {
                format!("value.{public}?.value")
            } else {
                dart_to_wire_expression(&format!("value.{public}"), &field.ty, field.name)
            };
            format!("  {wire}: {value},\n")
        })
        .collect::<String>();
    let from_signature = format!("{name} _{function}FromWire(wire.Wire{name} value)");
    let from_constructor = format!("{name}(");
    let (from_head, from_fields, from_tail) =
        dart_constructor_call(&from_signature, &from_constructor, &from_fields);
    let to_signature = format!("wire.Wire{name} _{function}ToWire({name} value)");
    let to_constructor = format!("wire.Wire{name}(");
    let (to_head, to_fields, to_tail) =
        dart_constructor_call(&to_signature, &to_constructor, &to_fields);
    format!("{from_head}{from_fields}{from_tail}{to_head}{to_fields}{to_tail}\n")
}

fn render_dart_union_converter(
    name: &str,
    variants: &[maxt_bindings_common::schema::Variant],
) -> String {
    let function = lower_camel(name);
    let from_arms = variants
        .iter()
        .map(|variant| {
            let suffix = pascal_case(variant.name);
            let constructor = dart_name(&suffix);
            match variant.fields.as_slice() {
                [] => format!(
                    "  wire.Wire{name}_{suffix}() => const {name}.{constructor}(),\n"
                ),
                [field] if field.name == "value" => format!(
                    "  wire.Wire{name}_{suffix}(:final field0) => {name}.{constructor}({}),\n",
                    dart_from_wire_value_expression("field0", &field.ty)
                ),
                fields => {
                    let pattern = fields
                        .iter()
                        .map(|field| {
                            format!(":final {}", dart_wire_field(field.name, &field.ty))
                        })
                        .collect::<Vec<_>>()
                        .join(", ");
                    let values = fields
                        .iter()
                        .map(|field| {
                            let public = snake_to_lower_camel(field.name);
                            let wire = dart_wire_field(field.name, &field.ty);
                            format!(
                                "    {public}: {},\n",
                                dart_from_wire_value_expression(&wire, &field.ty)
                            )
                        })
                        .collect::<String>();
                    format!(
                        "  wire.Wire{name}_{suffix}({pattern}) => {name}.{constructor}(\n{values}  ),\n"
                    )
                }
            }
        })
        .collect::<String>();
    let to_arms = variants
        .iter()
        .map(|variant| {
            let suffix = pascal_case(variant.name);
            let constructor = dart_name(&suffix);
            let wire_constructor = dart_wire_constructor(&constructor);
            match variant.fields.as_slice() {
                [] => format!(
                    "  {name}{suffix}() => const wire.Wire{name}.{wire_constructor}(),\n"
                ),
                [field] if field.name == "value" => format!(
                    "  {name}{suffix}(:final value) => wire.Wire{name}.{wire_constructor}({}),\n",
                    dart_to_wire_expression("value", &field.ty, field.name)
                ),
                fields => {
                    let pattern = fields
                        .iter()
                        .map(|field| format!(":final {}", snake_to_lower_camel(field.name)))
                        .collect::<Vec<_>>()
                        .join(", ");
                    let values = fields
                        .iter()
                        .map(|field| {
                            let public = snake_to_lower_camel(field.name);
                            let wire = dart_wire_field(field.name, &field.ty);
                            format!(
                                "    {wire}: {},\n",
                                dart_to_wire_expression(&public, &field.ty, field.name)
                            )
                        })
                        .collect::<String>();
                    format!(
                        "  {name}{suffix}({pattern}) => wire.Wire{name}.{wire_constructor}(\n{values}  ),\n"
                    )
                }
            }
        })
        .collect::<String>();
    format!(
        "{name} _{function}FromWire(wire.Wire{name} value) => switch (value) {{\n{from_arms}}};\n\nwire.Wire{name} _{function}ToWire({name} value) => switch (value) {{\n{to_arms}}};\n\n"
    )
}

fn dart_wire_constructor(name: &str) -> &str {
    match name {
        "required" => "required_",
        _ => name,
    }
}

