use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use maxt_bindings_common::schema::{Provider, Schema, TaggedUnion, Type, binding_schema};

const HEADER: &str = "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n";

fn main() {
    let check = match env::args().nth(1).as_deref() {
        None => false,
        Some("--check") => true,
        Some(argument) => panic!("unknown argument `{argument}`"),
    };
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("codegen crate must be below the repository root")
        .to_owned();
    let schema = binding_schema();
    let outputs = [
        (
            root.join("bindings/typescript/src/generated/contract.ts"),
            render_typescript(&schema),
        ),
        (
            root.join("bindings/python/python/maxt/_generated_contract.py"),
            render_python(&schema),
        ),
        (
            root.join("bindings/dart/lib/src/generated_contract.dart"),
            render_dart(&schema),
        ),
        (
            root.join("bindings/common/generated/api.md"),
            render_markdown(&schema),
        ),
    ];
    for (path, content) in outputs {
        if check {
            let actual = fs::read_to_string(&path)
                .unwrap_or_else(|error| panic!("{} is missing: {error}", path.display()));
            assert_eq!(actual, content, "{} is stale", path.display());
        } else {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).expect("generated output directory must be writable");
            }
            fs::write(&path, content)
                .unwrap_or_else(|error| panic!("failed to write {}: {error}", path.display()));
        }
    }
}

fn quoted(values: impl IntoIterator<Item = impl AsRef<str>>) -> String {
    values
        .into_iter()
        .map(|value| format!("\"{}\"", value.as_ref()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn snake_case(value: &str) -> String {
    let mut output = String::with_capacity(value.len());
    for character in value.chars() {
        if character.is_ascii_uppercase() {
            if !output.is_empty() {
                output.push('_');
            }
            output.push(character.to_ascii_lowercase());
        } else {
            output.push(character);
        }
    }
    output
}

fn ts_type(value: &Type) -> String {
    match value {
        Type::String => "string".to_owned(),
        Type::Boolean => "boolean".to_owned(),
        Type::Number => "number".to_owned(),
        Type::Named(name) => (*name).to_owned(),
        Type::Optional(value) => format!("{} | null", ts_type(value)),
        Type::List(value) => format!("readonly {}[]", ts_type(value)),
        Type::Tuple(values) => format!(
            "readonly [{}]",
            values.iter().map(ts_type).collect::<Vec<_>>().join(", ")
        ),
    }
}

fn render_typescript(schema: &Schema) -> String {
    let mut output = String::from(HEADER);
    output.push_str("\nexport type DecimalWire = string;\nexport type TimestampWire = string;\n");
    output.push_str("export type MarketKindWire = \"spot\" | \"perpetual\";\n\n");
    for record in &schema.records {
        output.push_str(&format!(
            "export interface {}{} {{\n",
            record.name,
            type_parameters(record.type_parameters)
        ));
        for field in &record.fields {
            output.push_str(&format!(
                "  readonly {}: {};\n",
                field.name,
                ts_type(&field.ty)
            ));
        }
        output.push_str("}\n\n");
    }
    for union in &schema.unions {
        render_ts_union(&mut output, union);
    }
    output.push_str(&format!(
        "export const EXCHANGES = [{}] as const;\n",
        quoted(&schema.exchanges)
    ));
    output.push_str(&format!(
        "export const FEATURES = [{}] as const;\n",
        quoted(&schema.features)
    ));
    output.push_str(&format!(
        "export const ERROR_VARIANTS = [{}] as const;\n",
        quoted(schema.errors)
    ));
    output.push_str(&format!(
        "export const ADAPTER_OPERATIONS = [{}] as const;\n",
        quoted(
            schema
                .adapter_operations
                .iter()
                .map(|operation| operation.language_name)
        )
    ));
    output.push_str(&format!(
        "export const CLIENT_MEMBERS = [{}] as const;\n",
        quoted(schema.client_members)
    ));
    output.push_str("export const PROVIDER_METHODS = {\n");
    for provider in schema.providers {
        output.push_str(&format!(
            "  {}: [{}],\n",
            provider.exchange,
            quoted(provider.methods)
        ));
    }
    output.push_str("} as const;\n");
    output
}

fn render_ts_union(output: &mut String, union: &TaggedUnion) {
    output.push_str(&format!(
        "export type {}{} =\n",
        union.name,
        type_parameters(union.type_parameters)
    ));
    for (index, variant) in union.variants.iter().enumerate() {
        output.push_str(if index == 0 { "  | {" } else { "\n  | {" });
        output.push_str(&format!(" readonly kind: \"{}\";", variant.name));
        for field in &variant.fields {
            output.push_str(&format!(
                " readonly {}: {};",
                field.name,
                ts_type(&field.ty)
            ));
        }
        output.push_str(" }");
    }
    output.push_str(";\n\n");
}

fn type_parameters(values: &[&str]) -> String {
    if values.is_empty() {
        String::new()
    } else {
        format!("<{}>", values.join(", "))
    }
}

fn render_python(schema: &Schema) -> String {
    format!(
        "# Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\nEXCHANGES = ({},)\nFEATURES = ({},)\nERROR_VARIANTS = ({},)\nADAPTER_OPERATIONS = ({},)\nCLIENT_MEMBERS = ({},)\nPROVIDER_METHODS = {{\n{}}}\n",
        python_items(&schema.exchanges),
        python_items(&schema.features),
        python_items(schema.errors),
        python_items(
            &schema
                .adapter_operations
                .iter()
                .map(|value| value.rust_name)
                .collect::<Vec<_>>(),
        ),
        python_owned_items(schema.client_members.iter().map(|value| snake_case(value))),
        schema
            .providers
            .iter()
            .map(render_python_provider)
            .collect::<String>(),
    )
}

fn python_items(values: &[&str]) -> String {
    values
        .iter()
        .map(|value| format!("\"{value}\""))
        .collect::<Vec<_>>()
        .join(", ")
}

fn python_owned_items(values: impl IntoIterator<Item = String>) -> String {
    values
        .into_iter()
        .map(|value| format!("\"{value}\""))
        .collect::<Vec<_>>()
        .join(", ")
}

fn render_python_provider(provider: &Provider) -> String {
    format!(
        "    \"{}\": ({},),\n",
        provider.exchange,
        python_owned_items(provider.methods.iter().map(|value| snake_case(value)))
    )
}

fn render_dart(schema: &Schema) -> String {
    let mut output =
        String::from("// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\n");
    output.push_str(&format!(
        "const exchanges = {};\n",
        dart_list(&schema.exchanges, "")
    ));
    output.push_str(&format!(
        "const features = {};\n",
        dart_list(&schema.features, "")
    ));
    output.push_str(&format!(
        "const errorVariants = {};\n",
        dart_list(schema.errors, "")
    ));
    let operations = schema
        .adapter_operations
        .iter()
        .map(|value| value.language_name)
        .collect::<Vec<_>>();
    output.push_str(&format!(
        "const adapterOperations = {};\n",
        dart_list(&operations, "")
    ));
    output.push_str(&format!(
        "const clientMembers = {};\n",
        dart_list(schema.client_members, "")
    ));
    output.push_str("const providerMethods = <String, List<String>>{\n");
    for provider in schema.providers {
        output.push_str(&format!(
            "  '{}': {},\n",
            provider.exchange,
            dart_list(provider.methods, "  ")
        ));
    }
    output.push_str("};\n");
    output
}

fn dart_list(values: &[&str], indent: &str) -> String {
    let joined = values
        .iter()
        .map(|value| format!("'{value}'"))
        .collect::<Vec<_>>()
        .join(", ");
    if joined.len() <= 60 {
        format!("<String>[{joined}]")
    } else {
        let items = values
            .iter()
            .map(|value| format!("{indent}  '{value}',\n"))
            .collect::<String>();
        format!("<String>[\n{items}{indent}]")
    }
}

fn render_markdown(schema: &Schema) -> String {
    let mut output = String::from(
        "<!-- Generated by `cargo run -p maxt-bindings-codegen`. Do not edit. -->\n\n# Binding contract\n\n## Adapter operations\n\n| Rust / Python | Dart / TypeScript |\n| --- | --- |\n",
    );
    for operation in schema.adapter_operations {
        output.push_str(&format!(
            "| `{}` | `{}` |\n",
            operation.rust_name, operation.language_name
        ));
    }
    output.push_str("\n## Provider-specific API\n\n| Exchange | Adapter | Python | Dart / TypeScript |\n| --- | --- | --- | --- |\n");
    for provider in schema.providers {
        let methods = provider
            .methods
            .iter()
            .map(|method| format!("`{method}`"))
            .collect::<Vec<_>>()
            .join(", ");
        let python_methods = provider
            .methods
            .iter()
            .map(|method| format!("`{}`", snake_case(method)))
            .collect::<Vec<_>>()
            .join(", ");
        output.push_str(&format!(
            "| {} | `{}` | {} | {} |\n",
            provider.exchange, provider.adapter, python_methods, methods
        ));
    }
    output
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_typescript_contains_every_contract_axis() {
        let output = render_typescript(&binding_schema());
        for expected in [
            "MarketWire",
            "SizeWire",
            "EXCHANGES",
            "FEATURES",
            "ADAPTER_OPERATIONS",
            "CLIENT_MEMBERS",
            "PROVIDER_METHODS",
        ] {
            assert!(output.contains(expected), "missing {expected}");
        }
    }

    #[test]
    fn python_names_are_derived_from_the_same_contract() {
        assert_eq!(snake_case("orderBook"), "order_book");
        assert_eq!(snake_case("usdMCreateListenKey"), "usd_m_create_listen_key");
    }
}
