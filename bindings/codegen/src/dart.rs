use maxt_bindings_common::schema::{
    ApiType, Argument, ClientComposition, Field, Operation, ProviderMethodKind, Schema, Type,
};

pub(crate) fn render(schema: &Schema) -> String {
    let mut output =
        String::from("// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\n");
    output.push_str(&format!(
        "const exchanges = {};\n",
        list(&schema.exchanges, "")
    ));
    output.push_str(&format!(
        "const features = {};\n",
        list(&schema.features, "")
    ));
    output.push_str(&format!(
        "const errorVariants = {};\n",
        list(schema.errors, "")
    ));
    let operations = schema
        .adapter_operations
        .iter()
        .map(|value| value.language_name)
        .collect::<Vec<_>>();
    output.push_str(&format!(
        "const adapterOperations = {};\n",
        list(&operations, "")
    ));
    output.push_str(&format!(
        "const clientMembers = {};\n",
        list(schema.client_members, "")
    ));
    output.push_str("const providerMethods = <String, List<String>>{\n");
    for provider in schema.providers {
        let methods = provider
            .methods
            .iter()
            .map(|method| method.name)
            .collect::<Vec<_>>();
        output.push_str(&format!(
            "  '{}': {},\n",
            provider.exchange,
            list(&methods, "  ")
        ));
    }
    output.push_str("};\n");
    output
}

pub(crate) fn render_identifiers(schema: &Schema) -> String {
    let mut output =
        String::from("// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\n");

    for (index, identifier) in schema.identifiers.iter().enumerate() {
        if identifier.open {
            render_open_identifier(&mut output, identifier);
        } else {
            render_closed_identifier(&mut output, identifier);
        }
        if index + 1 < schema.identifiers.len() {
            output.push('\n');
        }
    }

    output
}

pub(crate) fn render_models(schema: &Schema) -> String {
    const HANDWRITTEN: &[&str] = &[
        "Market",
        "MarketInfo",
        "Trade",
        "Level",
        "OrderBook",
        "Ticker",
        "Candle",
        "Balance",
        "Order",
        "Position",
        "MarginSummary",
        "FundingRate",
        "FundingPayment",
        "CandleRequest",
        "OrderRequest",
        "StreamConfig",
        "Subscription",
        "HistoryRequest",
        "MarginRequest",
        "UpbitMarketEvent",
        "BithumbMarketAlert",
        "BinanceSymbolFilters",
        "BinanceSpotOrderDetail",
        "HyperliquidLedgerEntry",
        "HyperliquidAssetContext",
    ];
    let generated = schema
        .models
        .iter()
        .copied()
        .filter(|name| !HANDWRITTEN.contains(name))
        .collect::<Vec<_>>();
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\npart of 'models.dart';\n",
    );
    for name in generated {
        if let Some(record) = schema
            .records
            .iter()
            .find(|record| record.name == format!("{name}Wire"))
        {
            output.push_str(&render_dart_model_record(name, &record.fields));
        } else if let Some(union) = schema
            .unions
            .iter()
            .find(|union| union.name == format!("{name}Wire"))
        {
            output.push_str(&render_dart_model_union(name, &union.variants));
        } else {
            panic!("generated Dart model {name} has no wire shape");
        }
    }
    output
}

fn render_dart_model_record(name: &str, fields: &[Field]) -> String {
    let asset = fields.iter().find(|field| field.name == "asset");
    let normalizes_asset = asset.is_some_and(|field| {
        field.ty == Type::String || field.ty == Type::Optional(Box::new(Type::String))
    });
    let argument = |field: &Field| {
        let public = snake_to_lower_camel(field.name);
        if name == "OrderHistoryRequest" && field.name == "statuses" {
            return "this.statuses = const []".to_owned();
        }
        if normalizes_asset && field.name == "asset" {
            let required = dart_required(&field.ty);
            return format!("{required}{} asset", dart_schema_type(field));
        }
        let required = dart_required(&field.ty);
        format!("{required}this.{public}")
    };
    let arguments = fields
        .iter()
        .map(|field| format!("    {},\n", argument(field)))
        .collect::<String>();
    let initializer = match asset.map(|field| &field.ty) {
        Some(Type::String) => " : asset = _asciiUpper(asset)",
        Some(Type::Optional(inner)) if **inner == Type::String => {
            " : asset = asset == null ? null : _asciiUpper(asset)"
        }
        _ => "",
    };
    let declarations = fields
        .iter()
        .map(|field| {
            format!(
                "  final {} {};\n",
                dart_schema_type(field),
                snake_to_lower_camel(field.name)
            )
        })
        .collect::<String>();
    let const_keyword = if normalizes_asset { "" } else { "const " };
    let flat_arguments = fields.iter().map(argument).collect::<Vec<_>>().join(", ");
    let flat_signature = format!("  {const_keyword}{name}({{{flat_arguments}}})");
    let constructor = if flat_signature.chars().count() <= 80 {
        let declaration = format!("{flat_signature}{initializer};");
        if declaration.chars().count() <= 80 {
            format!("{declaration}\n")
        } else {
            format!("{flat_signature}\n    {};\n", initializer.trim())
        }
    } else {
        format!("  {const_keyword}{name}({{\n{arguments}  }}){initializer};\n")
    };
    format!("\nfinal class {name} {{\n{constructor}\n{declarations}}}\n")
}

fn render_dart_model_union(
    name: &str,
    variants: &[maxt_bindings_common::schema::Variant],
) -> String {
    let factories = variants
        .iter()
        .map(|variant| {
            let suffix = pascal_case(variant.name);
            let constructor = dart_name(&suffix);
            let result = format!("{name}{suffix}");
            let signature = match variant.fields.as_slice() {
                [] => format!("  const factory {name}.{constructor}()"),
                [field] if field.name == "value" => format!(
                    "  const factory {name}.{constructor}({} value)",
                    dart_schema_type(field)
                ),
                fields => {
                    let flat_arguments = fields
                        .iter()
                        .map(|field| {
                            let required = dart_required(&field.ty);
                            format!(
                                "{required}{} {}",
                                dart_schema_type(field),
                                snake_to_lower_camel(field.name)
                            )
                        })
                        .collect::<Vec<_>>()
                        .join(", ");
                    let flat =
                        format!("  const factory {name}.{constructor}({{{flat_arguments}}})");
                    if flat.chars().count() <= 80 {
                        flat
                    } else {
                        let arguments = fields
                            .iter()
                            .map(|field| {
                                let required = dart_required(&field.ty);
                                format!(
                                    "    {required}{} {},\n",
                                    dart_schema_type(field),
                                    snake_to_lower_camel(field.name)
                                )
                            })
                            .collect::<String>();
                        format!("  const factory {name}.{constructor}({{\n{arguments}  }})")
                    }
                }
            };
            let declaration = format!("{signature} = {result};");
            if declaration.lines().count() > 1 || declaration.chars().count() <= 80 {
                format!("{declaration}\n")
            } else {
                format!("{signature} =\n      {result};\n")
            }
        })
        .collect::<String>();
    let classes = variants
        .iter()
        .map(|variant| {
            let suffix = pascal_case(variant.name);
            match variant.fields.as_slice() {
                [] => format!(
                    "\nfinal class {name}{suffix} extends {name} {{\n  const {name}{suffix}();\n}}\n"
                ),
                [field] if field.name == "value" => format!(
                    "\nfinal class {name}{suffix} extends {name} {{\n  const {name}{suffix}(this.value);\n\n  final {} value;\n}}\n",
                    dart_schema_type(field)
                ),
                fields => {
                    let flat_arguments = fields
                        .iter()
                        .map(|field| {
                            let required = dart_required(&field.ty);
                            format!("{required}this.{}", snake_to_lower_camel(field.name))
                        })
                        .collect::<Vec<_>>()
                        .join(", ");
                    let flat_constructor =
                        format!("  const {name}{suffix}({{{flat_arguments}}});");
                    let constructor = if flat_constructor.chars().count() <= 80 {
                        format!("{flat_constructor}\n")
                    } else {
                        let arguments = fields
                        .iter()
                        .map(|field| {
                            let required = dart_required(&field.ty);
                            format!(
                                "    {required}this.{},\n",
                                snake_to_lower_camel(field.name)
                            )
                        })
                        .collect::<String>();
                        format!("  const {name}{suffix}({{\n{arguments}  }});\n")
                    };
                    let declarations = fields
                        .iter()
                        .map(|field| {
                            format!(
                                "  final {} {};\n",
                                dart_schema_type(field),
                                snake_to_lower_camel(field.name)
                            )
                        })
                        .collect::<String>();
                    format!(
                        "\nfinal class {name}{suffix} extends {name} {{\n{constructor}\n{declarations}}}\n"
                    )
                }
            }
        })
        .collect::<String>();
    format!("\nsealed class {name} {{\n  const {name}();\n\n{factories}}}\n{classes}")
}

fn dart_schema_type(field: &Field) -> String {
    if field.name == "cursor" {
        return "Cursor?".to_owned();
    }
    dart_schema_value_type(&field.ty)
}

fn dart_required(ty: &Type) -> &'static str {
    if matches!(ty, Type::Optional(_)) {
        ""
    } else {
        "required "
    }
}

fn dart_schema_value_type(ty: &Type) -> String {
    match ty {
        Type::String => "String".to_owned(),
        Type::Boolean => "bool".to_owned(),
        Type::Number => "int".to_owned(),
        Type::UnsignedInteger => "BigInt".to_owned(),
        Type::Decimal => "Decimal".to_owned(),
        Type::Timestamp => "Timestamp".to_owned(),
        Type::Identifier(name) => (*name).to_owned(),
        Type::Named(name) => name.strip_suffix("Wire").unwrap_or(name).to_owned(),
        Type::Optional(inner) => format!("{}?", dart_schema_value_type(inner)),
        Type::List(inner) => format!("List<{}>", dart_schema_value_type(inner)),
        Type::Tuple(items) => format!(
            "({})",
            items
                .iter()
                .map(dart_schema_value_type)
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

pub(crate) fn render_rust_models(schema: &Schema) -> String {
    const HANDWRITTEN: &[&str] = &[
        "Market",
        "MarketInfo",
        "Trade",
        "Level",
        "OrderBook",
        "Ticker",
        "Candle",
        "Balance",
        "Order",
        "Position",
        "MarginSummary",
        "FundingRate",
        "FundingPayment",
        "CandleRequest",
        "OrderRequest",
        "StreamConfig",
        "Subscription",
        "HistoryRequest",
        "MarginRequest",
        "UpbitMarketEvent",
        "BithumbMarketAlert",
        "BinanceSymbolFilters",
        "BinanceSpotOrderDetail",
        "HyperliquidLedgerEntry",
        "HyperliquidAssetContext",
    ];
    let generated = schema
        .models
        .iter()
        .copied()
        .filter(|name| !HANDWRITTEN.contains(name))
        .collect::<Vec<_>>();
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\nuse super::*;\n",
    );
    let network = schema.identifier("Network").expect("Network schema");
    output.push_str(
        "\npub(crate) fn network_from_wire(value: String) -> maxt::Network {\n    match value.as_str() {\n",
    );
    for variant in network.variants {
        output.push_str(&format!(
            "        \"{}\" => maxt::Network::{},\n",
            variant.wire_name, variant.rust_name
        ));
    }
    output.push_str(
        "        _ => maxt::Network::Other(value),\n    }\n}\n\npub(crate) fn network_to_wire(value: maxt::Network) -> String {\n    value.id().to_owned()\n}\n",
    );
    for name in ["WithdrawalStatus", "DepositStatus"] {
        output.push_str(&render_rust_wire_identifier(
            schema.identifier(name).expect("wallet status schema"),
        ));
    }
    for name in &generated {
        if let Some(record) = schema
            .records
            .iter()
            .find(|record| record.name == format!("{name}Wire"))
        {
            output.push_str(&render_rust_wire_record(schema, name, &record.fields));
        } else if let Some(union) = schema
            .unions
            .iter()
            .find(|union| union.name == format!("{name}Wire"))
        {
            output.push_str(&render_rust_wire_union(schema, name, &union.variants));
        }
    }
    let mut pages = Vec::new();
    for operation in schema.adapter_operations {
        let ApiType::Page(name) = operation.result else {
            continue;
        };
        if !matches!(name, "FundingRate" | "FundingPayment") && !pages.contains(&name) {
            output.push_str(&render_rust_wire_page(name));
            pages.push(name);
        }
    }
    output
}

fn render_rust_wire_identifier(identifier: &maxt_bindings_common::schema::Identifier) -> String {
    let name = identifier.name;
    let variants = identifier
        .variants
        .iter()
        .map(|variant| format!("    {},\n", variant.rust_name))
        .collect::<String>();
    let to_arms = identifier
        .variants
        .iter()
        .map(|variant| {
            format!(
                "            maxt::{name}::{} => Self::{},\n",
                variant.rust_name, variant.rust_name
            )
        })
        .collect::<String>();
    let fallback = identifier
        .variants
        .iter()
        .find(|variant| variant.rust_name == "Unknown")
        .map(|_| "            _ => Self::Unknown,\n")
        .unwrap_or("            _ => unreachable!(\"new identifier variant requires a Dart wire variant\"),\n");
    let from_arms = identifier
        .variants
        .iter()
        .map(|variant| {
            format!(
                "            Wire{name}::{} => Self::{},\n",
                variant.rust_name, variant.rust_name
            )
        })
        .collect::<String>();
    format!(
        "\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum Wire{name} {{\n{variants}}}\n\nimpl From<maxt::{name}> for Wire{name} {{\n    fn from(value: maxt::{name}) -> Self {{\n        match value {{\n{to_arms}{fallback}        }}\n    }}\n}}\n\nimpl From<Wire{name}> for maxt::{name} {{\n    fn from(value: Wire{name}) -> Self {{\n        match value {{\n{from_arms}        }}\n    }}\n}}\n"
    )
}

fn render_rust_wire_record(schema: &Schema, name: &str, fields: &[Field]) -> String {
    let declarations = fields
        .iter()
        .map(|field| {
            format!(
                "    pub {}: {},\n",
                rust_wire_field(field.name, &field.ty),
                rust_schema_type(schema, field)
            )
        })
        .collect::<String>();
    let to_fields = fields
        .iter()
        .map(|field| {
            format!(
                "            {}: {},\n",
                rust_wire_field(field.name, &field.ty),
                rust_core_to_wire(schema, field, &format!("value.{}", field.name))
            )
        })
        .collect::<String>();
    let from_fields = fields
        .iter()
        .map(|field| {
            format!(
                "            {}: {},\n",
                field.name,
                rust_wire_to_core(
                    schema,
                    field,
                    &format!("value.{}", rust_wire_field(field.name, &field.ty))
                )
            )
        })
        .collect::<String>();
    let from_body = if name == "TransferLookupRequest" {
        format!(
            "        let request = Self {{\n{from_fields}        }};\n        request.validate().map_err(NativeError::from)?;\n        Ok(request)"
        )
    } else {
        format!("        Ok(Self {{\n{from_fields}        }})")
    };
    format!(
        "\n#[derive(Debug, Clone, PartialEq, Eq)]\npub struct Wire{name} {{\n{declarations}}}\n\nimpl From<maxt::{name}> for Wire{name} {{\n    fn from(value: maxt::{name}) -> Self {{\n        Self {{\n{to_fields}        }}\n    }}\n}}\n\nimpl TryFrom<Wire{name}> for maxt::{name} {{\n    type Error = NativeError;\n\n    fn try_from(value: Wire{name}) -> Result<Self, Self::Error> {{\n{from_body}\n    }}\n}}\n"
    )
}

fn render_rust_wire_union(
    schema: &Schema,
    name: &str,
    variants: &[maxt_bindings_common::schema::Variant],
) -> String {
    let declarations = variants
        .iter()
        .map(|variant| {
            let rust = pascal_case(variant.name);
            match variant.fields.as_slice() {
                [] => format!("    {rust},\n"),
                [field] if field.name == "value" => {
                    format!("    {rust}({}),\n", rust_schema_type(schema, field))
                }
                fields => {
                    let fields = fields
                        .iter()
                        .map(|field| {
                            format!(
                                "        {}: {},\n",
                                field.name,
                                rust_schema_type(schema, field)
                            )
                        })
                        .collect::<String>();
                    format!("    {rust} {{\n{fields}    }},\n")
                }
            }
        })
        .collect::<String>();
    let to_arms = variants
        .iter()
        .map(|variant| {
            let rust = pascal_case(variant.name);
            match variant.fields.as_slice() {
                [] => format!("            maxt::{name}::{rust} => Self::{rust},\n"),
                [field] if field.name == "value" => format!(
                    "            maxt::{name}::{rust}(value) => Self::{rust}({}),\n",
                    rust_core_to_wire(schema, field, "value")
                ),
                fields => {
                    let pattern = fields
                        .iter()
                        .map(|field| field.name)
                        .collect::<Vec<_>>()
                        .join(", ");
                    let values = fields
                        .iter()
                        .map(|field| {
                            rust_field_initializer(
                                field.name,
                                rust_core_to_wire(schema, field, field.name),
                            )
                        })
                        .collect::<String>();
                    format!(
                        "            maxt::{name}::{rust} {{ {pattern} }} => Self::{rust} {{\n{values}            }},\n"
                    )
                }
            }
        })
        .collect::<String>();
    let from_arms = variants
        .iter()
        .map(|variant| {
            let rust = pascal_case(variant.name);
            match variant.fields.as_slice() {
                [] => format!("            Wire{name}::{rust} => Self::{rust},\n"),
                [field] if field.name == "value" => format!(
                    "            Wire{name}::{rust}(value) => Self::{rust}({}),\n",
                    rust_wire_to_core(schema, field, "value")
                ),
                fields => {
                    let pattern = fields
                        .iter()
                        .map(|field| field.name)
                        .collect::<Vec<_>>()
                        .join(", ");
                    let values = fields
                        .iter()
                        .map(|field| {
                            rust_field_initializer(
                                field.name,
                                rust_wire_to_core(schema, field, field.name),
                            )
                        })
                        .collect::<String>();
                    format!(
                        "            Wire{name}::{rust} {{ {pattern} }} => Self::{rust} {{\n{values}            }},\n"
                    )
                }
            }
        })
        .collect::<String>();
    format!(
        "\n#[derive(Debug, Clone, PartialEq, Eq)]\npub enum Wire{name} {{\n{declarations}}}\n\nimpl From<maxt::{name}> for Wire{name} {{\n    fn from(value: maxt::{name}) -> Self {{\n        match value {{\n{to_arms}            _ => unreachable!(\"new {name} variant requires a Dart wire variant\"),\n        }}\n    }}\n}}\n\nimpl TryFrom<Wire{name}> for maxt::{name} {{\n    type Error = NativeError;\n\n    fn try_from(value: Wire{name}) -> Result<Self, Self::Error> {{\n        Ok(match value {{\n{from_arms}        }})\n    }}\n}}\n"
    )
}

fn rust_field_initializer(name: &str, value: String) -> String {
    if value == name {
        format!("                {name},\n")
    } else {
        format!("                {name}: {value},\n")
    }
}

fn render_rust_wire_page(name: &str) -> String {
    format!(
        "\n#[derive(Debug, Clone, PartialEq, Eq)]\npub struct Wire{name}Page {{\n    pub items: Vec<Wire{name}>,\n    pub next: Option<String>,\n}}\n\nimpl From<maxt::Page<maxt::{name}>> for Wire{name}Page {{\n    fn from(value: maxt::Page<maxt::{name}>) -> Self {{\n        Self {{\n            items: value.items.into_iter().map(Into::into).collect(),\n            next: value.next.map(|cursor| cursor.as_str().to_owned()),\n        }}\n    }}\n}}\n\nimpl TryFrom<Wire{name}Page> for maxt::Page<maxt::{name}> {{\n    type Error = NativeError;\n\n    fn try_from(value: Wire{name}Page) -> Result<Self, Self::Error> {{\n        Ok(Self {{\n            items: value.items.into_iter().map(TryInto::try_into).collect::<Result<_, _>>()?,\n            next: value.next.map(maxt::Cursor::new),\n        }})\n    }}\n}}\n"
    )
}

fn rust_schema_type(schema: &Schema, field: &Field) -> String {
    if field.name == "cursor" {
        return "Option<String>".to_owned();
    }
    rust_schema_value_type(schema, &field.ty)
}

fn rust_schema_value_type(schema: &Schema, ty: &Type) -> String {
    match ty {
        Type::String | Type::Decimal => "String".to_owned(),
        Type::Boolean => "bool".to_owned(),
        Type::Number => "u32".to_owned(),
        Type::UnsignedInteger => "u64".to_owned(),
        Type::Timestamp => "i64".to_owned(),
        Type::Identifier(name) if schema.identifier(name).expect("identifier").open => {
            "String".to_owned()
        }
        Type::Identifier(name) => format!("Wire{name}"),
        Type::Named(name) => format!("Wire{}", name.strip_suffix("Wire").unwrap_or(name)),
        Type::Optional(inner) => format!("Option<{}>", rust_schema_value_type(schema, inner)),
        Type::List(inner) => format!("Vec<{}>", rust_schema_value_type(schema, inner)),
        Type::Tuple(items) => format!(
            "({})",
            items
                .iter()
                .map(|value| rust_schema_value_type(schema, value))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn rust_core_to_wire(schema: &Schema, field: &Field, value: &str) -> String {
    if field.name == "cursor" {
        return format!("{value}.map(|cursor| cursor.as_str().to_owned())");
    }
    rust_core_to_wire_value(schema, &field.ty, value)
}

fn rust_core_to_wire_value(schema: &Schema, ty: &Type, value: &str) -> String {
    match ty {
        Type::String | Type::Boolean | Type::Number | Type::UnsignedInteger => value.to_owned(),
        Type::Decimal => format!("decimal_to_wire({value})"),
        Type::Timestamp => format!("timestamp_to_wire({value})"),
        Type::Identifier(name) if schema.identifier(name).expect("identifier").open => {
            format!("network_to_wire({value})")
        }
        Type::Identifier(_) | Type::Named(_) => format!("{value}.into()"),
        Type::Optional(inner) => match inner.as_ref() {
            Type::String | Type::Boolean | Type::Number | Type::UnsignedInteger => value.to_owned(),
            Type::Decimal => format!("{value}.map(decimal_to_wire)"),
            Type::Timestamp => format!("{value}.map(timestamp_to_wire)"),
            Type::Identifier(name) if schema.identifier(name).expect("identifier").open => {
                format!("{value}.map(network_to_wire)")
            }
            Type::Identifier(_) | Type::Named(_) => format!("{value}.map(Into::into)"),
            other => panic!("unsupported generated Dart Rust optional: {other:?}"),
        },
        Type::List(inner) => match inner.as_ref() {
            Type::String | Type::Boolean | Type::Number | Type::UnsignedInteger => value.to_owned(),
            Type::Decimal => format!("{value}.into_iter().map(decimal_to_wire).collect()"),
            Type::Named(_) | Type::Identifier(_) => {
                format!("{value}.into_iter().map(Into::into).collect()")
            }
            other => panic!("unsupported generated Dart Rust list: {other:?}"),
        },
        Type::Tuple(_) => panic!("generated Dart wallet models do not use tuples"),
    }
}

fn rust_wire_to_core(schema: &Schema, field: &Field, value: &str) -> String {
    if field.name == "cursor" {
        return format!("{value}.map(maxt::Cursor::new)");
    }
    rust_wire_to_core_value(schema, &field.ty, value, field.name)
}

fn rust_wire_to_core_value(schema: &Schema, ty: &Type, value: &str, field: &str) -> String {
    match ty {
        Type::String | Type::Boolean | Type::Number | Type::UnsignedInteger => value.to_owned(),
        Type::Decimal => {
            format!("decimal_from_wire(&{value}, \"{field}\").map_err(NativeError::from)?")
        }
        Type::Timestamp => format!("Timestamp::from_nanos({value})"),
        Type::Identifier(name) if schema.identifier(name).expect("identifier").open => {
            format!("network_from_wire({value})")
        }
        Type::Identifier(_) => format!("{value}.into()"),
        Type::Named("MarketWire") => format!("{value}.into()"),
        Type::Named(_) => format!("{value}.try_into()?"),
        Type::Optional(inner) => match inner.as_ref() {
            Type::String | Type::Boolean | Type::Number | Type::UnsignedInteger => value.to_owned(),
            Type::Decimal => format!(
                "{value}.as_deref().map(|value| decimal_from_wire(value, \"{field}\")).transpose().map_err(NativeError::from)?"
            ),
            Type::Timestamp => format!("{value}.map(Timestamp::from_nanos)"),
            Type::Identifier(name) if schema.identifier(name).expect("identifier").open => {
                format!("{value}.map(network_from_wire)")
            }
            Type::Identifier(_) => format!("{value}.map(Into::into)"),
            Type::Named("MarketWire") => format!("{value}.map(Into::into)"),
            Type::Named(_) => format!("{value}.map(TryInto::try_into).transpose()?"),
            other => panic!("unsupported generated Dart Rust optional: {other:?}"),
        },
        Type::List(inner) => match inner.as_ref() {
            Type::String | Type::Boolean | Type::Number | Type::UnsignedInteger => value.to_owned(),
            Type::Decimal => format!(
                "{value}.into_iter().map(|value| decimal_from_wire(&value, \"{field}\").map_err(NativeError::from)).collect::<Result<_, _>>()?"
            ),
            Type::Identifier(_) => format!("{value}.into_iter().map(Into::into).collect()"),
            Type::Named(_) => {
                format!("{value}.into_iter().map(TryInto::try_into).collect::<Result<_, _>>()?")
            }
            other => panic!("unsupported generated Dart Rust list: {other:?}"),
        },
        Type::Tuple(_) => panic!("generated Dart wallet models do not use tuples"),
    }
}

