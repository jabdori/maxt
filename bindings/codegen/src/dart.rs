pub(crate) fn render_rust_adapter_dispatch(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\nuse super::*;\n\n#[rustfmt::skip]\npub(super) fn dispatch(call: CommonAdapterCall) -> Option<(AdapterCall, ExpectedReply)> {\n    match call {\n",
    );
    for operation in schema.adapter_operations.iter().filter(|operation| {
        !matches!(
            operation.result,
            ApiType::MarketStream | ApiType::AccountStream
        )
    }) {
        let variant = pascal_case(operation.rust_name);
        let fields = operation
            .arguments
            .iter()
            .map(|argument| snake_case(argument.name))
            .collect::<Vec<_>>();
        let pattern = if fields.is_empty() {
            format!("CommonAdapterCall::{variant}")
        } else {
            format!("CommonAdapterCall::{variant} {{ {} }}", fields.join(", "))
        };
        let mapped_fields = operation
            .arguments
            .iter()
            .map(|argument| {
                let name = snake_case(argument.name);
                let value = match argument.ty {
                    ApiType::Named(_) => format!("{name}.into()"),
                    ApiType::OptionalNamed(_) => format!("{name}.map(Into::into)"),
                    _ => name.clone(),
                };
                format!("{name}: {value}")
            })
            .collect::<Vec<_>>();
        let expected = if operation.result == ApiType::Unit {
            "Unit".to_owned()
        } else {
            variant.clone()
        };
        if mapped_fields.is_empty() {
            let arm = format!(
                "        {pattern} => Some((AdapterCall::{variant}, ExpectedReply::{expected})),\n"
            );
            if arm.trim_end().chars().count() <= 100 {
                output.push_str(&arm);
            } else {
                output.push_str(&format!(
                    "        {pattern} => {{\n            Some((AdapterCall::{variant}, ExpectedReply::{expected}))\n        }}\n"
                ));
            }
        } else {
            let inline_fields = mapped_fields
                .iter()
                .map(|field| {
                    let (name, value) = field.split_once(": ").expect("generated field");
                    if name == value {
                        name.to_owned()
                    } else {
                        field.clone()
                    }
                })
                .collect::<Vec<_>>()
                .join(", ");
            let inline = format!("            AdapterCall::{variant} {{ {inline_fields} }},\n");
            output.push_str(&format!("        {pattern} => Some((\n"));
            if inline.trim_end().chars().count() <= 100 {
                output.push_str(&inline);
            } else {
                output.push_str(&format!("            AdapterCall::{variant} {{\n"));
                for field in mapped_fields {
                    let (name, value) = field.split_once(": ").expect("generated field");
                    if name == value {
                        output.push_str(&format!("                {name},\n"));
                    } else {
                        output.push_str(&format!("                {field},\n"));
                    }
                }
                output.push_str("            },\n");
            }
            output.push_str(&format!(
                "            ExpectedReply::{expected},\n        )),\n"
            ));
        }
    }
    output.push_str("        _ => None,\n    }\n}\n");
    output
}

pub(crate) fn render_provider_guard(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n// ignore_for_file: unused_element\n\npart of 'adapters.dart';\n\nT _generatedProviderValue<T>() => throw StateError('compile-time API guard');\n\nvoid _generatedProviderGuard({\n",
    );
    for provider in schema.providers {
        output.push_str(&format!(
            "  required {} {},\n",
            provider.adapter, provider.exchange
        ));
    }
    output.push_str("}) {\n");
    for provider in schema.providers {
        for constructor in provider.constructors {
            let name = if constructor.name == "constructor" {
                provider.adapter.to_owned()
            } else {
                format!("{}.{}", provider.adapter, constructor.name)
            };
            let arguments = constructor
                .arguments
                .iter()
                .filter(|argument| argument.default.is_none())
                .map(|argument| format!("_generatedProviderValue<{}>()", dart_type(argument.ty)))
                .collect::<Vec<_>>()
                .join(", ");
            output.push_str(&format!("  {name}({arguments});\n"));
        }
        for method in provider.methods {
            if method.kind == ProviderMethodKind::Property {
                output.push_str(&format!("  {}.{};\n", provider.exchange, method.name));
                continue;
            }
            let arguments = method
                .arguments
                .iter()
                .filter(|argument| argument.default.is_none())
                .map(|argument| format!("_generatedProviderValue<{}>()", dart_type(argument.ty)))
                .collect::<Vec<_>>()
                .join(", ");
            let call = format!("  {}.{}({arguments});", provider.exchange, method.name);
            if call.chars().count() <= 80 || method.arguments.len() < 2 {
                output.push_str(&format!("{call}\n"));
            } else {
                output.push_str(&format!("  {}.{}(\n", provider.exchange, method.name));
                for argument in method
                    .arguments
                    .iter()
                    .filter(|argument| argument.default.is_none())
                {
                    output.push_str(&format!(
                        "    _generatedProviderValue<{}>(),\n",
                        dart_type(argument.ty)
                    ));
                }
                output.push_str("  );\n");
            }
        }
    }
    output.push_str("}\n");
    output
}

pub(crate) fn render_provider_methods(schema: &Schema) -> String {
    let mut output = String::from(
        "// Generated by `cargo run -p maxt-bindings-codegen`. Do not edit.\n\npart of 'adapters.dart';\n",
    );
    for provider in schema.providers {
        output.push_str(&format!(
            "\n/// {}-specific API extension.\nextension {}GeneratedMethods on {} {{\n",
            provider_display_name(provider.exchange),
            provider.adapter,
            provider.adapter
        ));
        for (index, method) in provider
            .methods
            .iter()
            .filter(|method| method.kind == ProviderMethodKind::Async)
            .enumerate()
        {
            if index > 0 {
                output.push('\n');
            }
            if uses_generated_native_provider_bridge(provider.exchange, method.rust_name) {
                output.push_str(&render_generated_provider_method(provider, method));
            } else {
                output.push_str(&provider_method_source(provider.exchange, method.rust_name));
            }
        }
        output.push_str("}\n");
    }
    output.push_str(&render_generated_provider_streams(schema));
    output
}

/// Emits the regular request/result path for the fixed provider batch.
///
/// The schema remains the single source of truth. Stream polling and close
/// mechanics are generated below as well; only the shared `_CloseableStream`
/// runtime itself is handwritten.
fn render_generated_provider_method(provider: &Provider, method: &ProviderMethod) -> String {
    match method.result {
        ApiType::ProviderMarketStream(event) => {
            render_generated_provider_stream_method(provider, method, event, false)
        }
        ApiType::ProviderAccountStream(event) => {
            render_generated_provider_stream_method(provider, method, event, true)
        }
        _ => {
            let call = format!(
                "_handle.{}({})",
                dart_native_provider_method_name(provider, method),
                method
                    .arguments
                    .iter()
                    .map(dart_provider_native_argument)
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            format!(
                "  /// Calls the {}-specific `{}` API.\n  Future<{}> {}({}) => _nativeFuture(\n    () => {call},\n  ).then({});\n",
                provider_display_name(provider.exchange),
                method.name,
                dart_type(method.result),
                method.name,
                dart_arguments(method.arguments),
                dart_provider_result_converter(method.result),
            )
        }
    }
}

fn render_generated_provider_stream_method(
    provider: &Provider,
    method: &ProviderMethod,
    event: &str,
    account: bool,
) -> String {
    let stream = provider_stream_type(event);
    let method_name = method.name;
    if method.rust_name == "subscribe_detailed" {
        return format!(
            "  /// Opens a market stream that preserves {}-native fields.\n  Future<{stream}> {method_name}(\n    Subscription subscription,\n  ) => subscribeDetailedWith(subscription, defaultStreamConfig());\n",
            provider_display_name(provider.exchange),
        );
    }
    if method.rust_name == "subscribe_detailed_account" {
        return format!(
            "  /// Opens an account stream that preserves {}-native fields.\n  Future<{stream}> {method_name}() =>\n      subscribeDetailedAccountWith(defaultStreamConfig());\n",
            provider_display_name(provider.exchange),
        );
    }

    let arguments = dart_arguments(method.arguments);
    let call_arguments = method
        .arguments
        .iter()
        .map(dart_provider_native_argument)
        .collect::<Vec<_>>()
        .join(", ");
    let native_call = dart_native_provider_method_name(provider, method);
    let exchange = pascal_case(provider.exchange);
    let kind = if account { "Account" } else { "Market" };
    let items = format!("_native{exchange}{kind}Items");
    let close = format!("native.native{}{}SubscriptionClose", exchange, kind);
    let config_check = if method
        .arguments
        .iter()
        .any(|argument| argument.name == "config")
    {
        "    validateStreamConfigIntegers(config);\n"
    } else {
        ""
    };
    format!(
        "  /// Opens a {} stream that preserves {}-native fields.\n  Future<{stream}> {method_name}({arguments}) async {{\n{config_check}    final handle = await _nativeFuture(\n      () => _handle.{native_call}({call_arguments}),\n    );\n    return {stream}(\n      {items}(handle),\n      onClose: () => _nativeFuture(\n        () => {close}(subscription: handle),\n      ),\n    );\n  }}\n",
        provider_display_name(provider.exchange),
        if account { "account" } else { "market" },
    )
}

fn render_generated_provider_streams(schema: &Schema) -> String {
    let entries = generated_provider_stream_entries(schema);
    if entries.is_empty() {
        return String::new();
    }
    let mut output = String::from("\n");
    for (exchange, event, account) in entries {
        let stream = provider_stream_type(event);
        let exchange_pascal = pascal_case(exchange);
        let kind = if account { "Account" } else { "Market" };
        output.push_str(&format!(
            "Stream<StreamItem<{event}>> _native{exchange_pascal}{kind}Items(\n  native_stream.Native{exchange_pascal}{kind}Subscription subscription,\n) async* {{\n  while (true) {{\n    final item = await _nativeFuture(\n      () => native.native{exchange_pascal}{kind}SubscriptionNext(\n        subscription: subscription,\n      ),\n    );\n    switch (item) {{\n      case native_stream.Wire{stream}Item_Event(:final field0):\n        yield StreamItem.event(_{}FromWire(field0));\n      case native_stream.Wire{stream}Item_Error(:final field0):\n        yield StreamItem.error(_nativeError(field0));\n      case native_stream.Wire{stream}Item_End():\n        return;\n    }}\n  }}\n}}\n\n",
            lower_camel(event),
        ));
    }
    output
}

